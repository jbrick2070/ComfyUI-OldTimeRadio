# BUG-LOCAL-129a: minimum byte size for the radio still PNG before we
# treat it as usable for static-segment generation. Catches 0-byte /
# truncated FLUX renders (BUG-LOCAL-121).
_MIN_RADIO_STILL_BYTES = 256

# BUG-LOCAL-129a: explicit container timebase for static segments
# generated by ffmpeg. HuMo clips ship with whatever timebase ffmpeg
# picked at save time (typically tbn=12800 for libx264 mp4). Force
# the same on static segments so the concat-demuxer pass downstream
# can `-c copy` without timestamp drift at the seam (Jeffrey's review
# Q3 catch, 2026-05-01).
_STATIC_SEGMENT_TIMEBASE = "12800"


def _resolve_radio_still_for_static(ledger: dict | None) -> Path | None:
    """Resolve the radio bookend PNG path for static-segment fallback.

    Mirrors the resolution order in
    ``batch_humo_render._resolve_radio_still_path`` so VideoComposite
    and BatchHumoRender stay in lockstep:

      1. ``ledger.radio_bookend_path`` (top-level)
      2. ``ledger.meta.radio_bookend_path``
      3. Filesystem fallback at
         ``output/otr/stills/radio_bookend_<episode_id>.png``

    Returns ``Path`` if a usable PNG exists (file present, size >=
    :data:`_MIN_RADIO_STILL_BYTES`), else ``None``. Hostile-input safe.
    """
    if not isinstance(ledger, dict):
        return None

    def _is_valid(p: Path) -> bool:
        try:
            if not p.is_file():
                return False
            return p.stat().st_size >= _MIN_RADIO_STILL_BYTES
        except Exception:  # noqa: BLE001
            return False

    cand = ledger.get("radio_bookend_path")
    if not cand:
        meta = ledger.get("meta") or {}
        if isinstance(meta, dict):
            cand = meta.get("radio_bookend_path")
    if cand:
        try:
            p = Path(cand)
        except Exception:  # noqa: BLE001
            p = None
        if p is not None and _is_valid(p):
            return p
        if p is not None:
            log.warning(
                "[VideoComposite/static] ledger radio_bookend_path=%s does "
                "not exist or is truncated; trying filesystem fallback",
                p,
            )

    eid_raw = ledger.get("episode_id")
    if not isinstance(eid_raw, str):
        return None
    eid = eid_raw.strip()
    if not eid or any(t in eid for t in ("/", "\\", "..", "\x00")):
        return None
    try:
        fs_path = otr_stills_dir(eid) / f"radio_bookend_{eid}.png"
    except Exception as exc:  # noqa: BLE001
        log.warning(
            "[VideoComposite/static] otr_stills_dir(%r) lookup failed: %s",
            eid, exc,
        )
        return None
    if _is_valid(fs_path):
        log.info(
            "[VideoComposite/static] radio still resolved via filesystem "
            "fallback: %s",
            fs_path,
        )
        return fs_path
    return None


def _render_loop_motion_segment(
    *,
    loop_mp4: Path,
    dur_s: float,
    canvas_w: int,
    canvas_h: int,
    canvas_fps: int,
    out_path: Path,
    ffmpeg: str,
) -> Path:
    """BUG-LOCAL-135 (2026-05-08): generate a motion-loop video segment
    by ffmpeg ``-stream_loop``'ing an existing LTX motion clip to fill
    the requested duration.  Replaces ``_render_static_radio_segment``
    for music / sfx / gap fills so the radio set retains subtle motion
    (vacuum-tube glow, dust motes, dial flicker) across the entire
    episode instead of dead-frozen frames in 47+ seconds of coverage
    that the static helper used to paint.

    Implementation invariants (parity with _render_static_radio_segment
    so concat-demuxer + ``-c copy`` accepts the segment):
      - ``-stream_loop -1 -i <loop_mp4>`` -- repeat input forever; the
        ``-frames:v`` cap below is what trims it to the requested dur.
      - ``-frames:v <int(round(dur_s * canvas_fps))>`` -- exact frame
        count, NOT ``-t``. Round-to-frame so seam drift is bounded
        +/- 0.5 frame at each gap, not accumulating.
      - ``-r <canvas_fps>`` -- output fps locked to canvas fps.
      - ``-video_track_timescale 12800`` -- match HuMo / static helper
        container timebase for clean concat.
      - ``-an`` -- strip the source clip's audio (master mix attaches
        in the final mux step, same as static-fill path; no double-mux
        of an LTX clip's own dialogue/announcer audio).
      - scale + pad to canvas_w x canvas_h (parity with static helper).
    """
    frame_count = max(1, int(round(float(dur_s) * float(canvas_fps))))
    out_path.parent.mkdir(parents=True, exist_ok=True)
    vf = (
        f"scale={canvas_w}:{canvas_h}:force_original_aspect_ratio=decrease,"
        f"pad={canvas_w}:{canvas_h}:(ow-iw)/2:(oh-ih)/2:color=black,"
        f"format=yuv420p"
    )
    cmd = [
        ffmpeg, "-y", "-loglevel", "error",
        "-stream_loop", "-1",
        "-i", str(loop_mp4),
        "-vf", vf,
        "-r", str(int(canvas_fps)),
        "-frames:v", str(frame_count),
        "-c:v", "libx264", "-pix_fmt", "yuv420p",
        "-crf", "18", "-preset", "fast",
        "-video_track_timescale", _STATIC_SEGMENT_TIMEBASE,
        "-an",
        str(out_path),
    ]
    subprocess.run(cmd, check=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    return out_path


def _resolve_loop_motion_for_fill(
    ledger: dict,
    clips_dir: Path,
    episode_dir: Path,
) -> "Path | None":
    """BUG-LOCAL-135 (2026-05-08): resolve the canonical motion loop
    used for music / sfx / gap fills.  Returns the first usable motion
    mp4 we can ffmpeg-loop, or ``None`` to fall back to the static-radio
    fill helper (BUG-LOCAL-129a).

    Lookup order (cheapest first, no extra render cost):
      1. ``<episode_dir>/loop/loop_radio_motion.mp4`` -- canonical
         pre-baked broadcast-set loop. Reserved for a future Phase 1
         producer that may render a generic 5s loop separately; not
         required for this pass.
      2. First ``clips[]`` entry with ``source_kind=ltx`` whose mp4
         lives on disk -- typically the announcer line.  The motion
         prompt is broadcast-set-flavoured (per
         ``_build_ltx_role_prompt``) so it works as a generic loop;
         reuses an existing render at zero extra wall time.
      3. Any per-line mp4 in ``clips_dir`` -- catch-all so the path
         still survives if the ledger ``clips[]`` array got partially
         clobbered by a save-race (the kind seen on 2026-05-08 where
         the music mirror's appended lines were lost).

    Empty-file guard: requires > 4 KiB so a 0-byte stub doesn't get
    promoted to "loop" and crash the ffmpeg subprocess.
    """
    canonical = episode_dir / "loop" / "loop_radio_motion.mp4"
    try:
        if canonical.is_file() and canonical.stat().st_size > 4096:
            return canonical
    except OSError:
        pass

    clips = ledger.get("clips")
    if isinstance(clips, list):
        for c in clips:
            if not isinstance(c, dict):
                continue
            if c.get("source_kind") != "ltx":
                continue
            mp4 = c.get("mp4_path")
            if not mp4:
                continue
            try:
                p = Path(str(mp4))
                if p.is_file() and p.stat().st_size > 4096:
                    return p
            except (OSError, ValueError):
                continue

    if clips_dir.is_dir():
        for p in sorted(clips_dir.glob("l*.mp4")):
            try:
                if p.stat().st_size > 4096:
                    return p
            except OSError:
                continue
    return None


def _render_static_radio_segment(
    *,
    radio_png: Path,
    dur_s: float,
    canvas_w: int,
    canvas_h: int,
    canvas_fps: int,
    out_path: Path,
    ffmpeg: str,
) -> Path:
    """BUG-LOCAL-129a: generate a deterministic static video segment
    from the radio bookend PNG, sized to the canvas dims, no audio,
    exact frame count, fixed timebase.

    Used to fill ledger lines that have no corresponding HuMo clip
    on disk (announcer / music_* / sfx in the post-BUG-129b world,
    or any line where BatchHumoRender failed to render a clip).

    Strict invariants (each catches a different Jeffrey-review gotcha):
      - ``-frames:v <int(round(dur_s * canvas_fps))>`` -- exact frame
        count, NOT ``-t``. Round-to-frame at generation time so
        cumulative drift across many static segments is bounded to
        +/- 0.5 frame at each seam, not accumulating.
      - ``-r <canvas_fps>`` -- output fps locked to canvas fps (must
        match HuMo's ``HUMO_FPS = 25`` exactly to avoid concat-demuxer
        frame-rate mismatch).
      - ``-video_track_timescale 12800`` -- match HuMo clip container
        timebase so concat-demuxer with ``-c copy`` produces a clean
        timestamp stream.
      - ``-an`` -- no audio. Master mix attaches in the final mux
        step, same as for HuMo clips.
      - libx264 yuv420p crf=18 preset=fast -- match the pillarbox
        re-encode profile so concat-demuxer with ``-c copy`` doesn't
        reject the stream.
      - scale + pad to canvas_w x canvas_h with center alignment so
        the still fills the canvas without distortion regardless of
        the source PNG aspect ratio.
    """
    frame_count = max(1, int(round(float(dur_s) * float(canvas_fps))))
    out_path.parent.mkdir(parents=True, exist_ok=True)
    # scale to fit-inside canvas, then pad to canvas dims (center).
    vf = (
        f"scale={canvas_w}:{canvas_h}:force_original_aspect_ratio=decrease,"
        f"pad={canvas_w}:{canvas_h}:(ow-iw)/2:(oh-ih)/2:color=black,"
        f"format=yuv420p"
    )
    cmd = [
        ffmpeg, "-y", "-loglevel", "error",
        "-loop", "1",
        "-i", str(radio_png),
        "-vf", vf,
        "-r", str(int(canvas_fps)),
        "-frames:v", str(frame_count),
        "-c:v", "libx264", "-pix_fmt", "yuv420p",
        "-crf", "18", "-preset", "fast",
        "-video_track_timescale", _STATIC_SEGMENT_TIMEBASE,
        "-an",
        str(out_path),
    ]
    subprocess.run(cmd, check=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    return out_path


def _ffprobe_dur(path: Path, ffprobe: str = "ffprobe") -> float | None:
    """Return mp4 duration in seconds, or None on failure."""
    try:
        r = subprocess.run(
            [ffprobe, "-v", "error",
             "-show_entries", "format=duration",
             "-of", "default=noprint_wrappers=1:nokey=1",
             str(path)],
            capture_output=True, text=True, check=True,
        )
        return float(r.stdout.strip())
    except Exception as exc:
        log.warning("[VideoComposite] ffprobe %s failed: %s", path, exc)
        return None


def _load_ledger_with_path(arg: str) -> tuple[dict, "Path | None"]:
    """Accept inline JSON, ledger.json path, .mp4 path (suffix-swap
    to ledger), or empty (auto-pick newest non-pending). Mirrors
    BatchHumoRender._load_ledger_with_path so wiring is consistent.

    Returns (ledger_dict, ledger_path_or_None). Path is None for
    inline JSON; BUG-LOCAL-089 final_video_path write-back skips
    in that case rather than synthesizing a new file.
    """
    s = (arg or "").strip()

    if not s:
        # S28 cleanbreak: dropped otr_legacy_audio_dir() from the
        # search list. Per-episode workspace is the only contract.
        audio_dirs = [
            otr_episodes_root(),
        ]
        cands = []
        for d in audio_dirs:
            if d.exists():
                cands.extend(
                    p for p in d.glob("*_ledger.json")
                    if not p.name.startswith("pending_")
                )
        if not cands:
            raise RuntimeError("VideoComposite: ledger_json empty and auto-pick found no ledger")
        p = max(cands, key=lambda x: x.stat().st_mtime)
        with open(p, "r", encoding="utf-8") as f:
            return json.load(f), p

    if s.startswith("{"):
        return json.loads(s), None

    p = Path(s)
    # .mp4 path -> swap suffix to _ledger.json (SignalLostVideo convention)
    if p.suffix.lower() == ".mp4":
        ledger_p = p.with_suffix("").parent / f"{p.stem}_ledger.json"
        if ledger_p.exists():
            with open(ledger_p, "r", encoding="utf-8") as f:
                return json.load(f), ledger_p
        # BUG-LOCAL-118 underscore-mismatch fallback: SignalLostVideo
        # writes the procgen .mp4 with a DOUBLE underscore before the
        # timestamp (`<title>__<ts>.mp4`) but the ledger is written
        # with a SINGLE underscore (`<title>_<ts>_ledger.json`). The
        # naive stem-swap above derives `<title>__<ts>_ledger.json` and
        # misses. Same fallback BatchLTXRender uses (logs at LTX entry
        # in comfyui_8000.log). Try collapsing the trailing double
        # underscore in the stem to a single underscore and re-look.
        stem = p.stem
        if "__" in stem:
            collapsed = stem.replace("__", "_")
            alt_ledger_p = ledger_p.parent / f"{collapsed}_ledger.json"
            if alt_ledger_p.exists():
                log.warning(
                    "[VideoComposite] BUG-LOCAL-118 underscore-mismatch "
                    "fallback: .mp4 stem %r had double underscores; "
                    "loaded matching ledger %r instead.",
                    stem, alt_ledger_p.name,
                )
                with open(alt_ledger_p, "r", encoding="utf-8") as f:
                    return json.load(f), alt_ledger_p
        raise RuntimeError(
            f"VideoComposite: derived ledger from .mp4 not found: {ledger_p} "
            f"(also tried single-underscore variant)"
        )

    if not p.exists():
        raise RuntimeError(f"VideoComposite: ledger path not found: {p}")
    with open(p, "r", encoding="utf-8") as f:
        return json.load(f), p


def _build_clip_timeline(
    ledger: dict,
    clips_dir: Path,
    fallback_clip_length: float,
    ffprobe: str = "ffprobe",
) -> list[tuple[Path, float, float]]:
    """Build [(clip_path, start_s, dur_s), ...] for every ledger line
    that has a clip on disk. Cumulative start_s across the timeline
    -- ignores ledger.start_s except as a hint (we trust the actual
    rendered clip duration over ledger arithmetic)."""
    lines = ledger.get("lines") or []
    timeline: list[tuple[Path, float, float]] = []
    cumulative = 0.0
    for ln in lines:
        line_id = str(ln.get("line_id") or "")
        if not line_id:
            continue
        clip_path = clips_dir / f"{line_id}.mp4"
        if not clip_path.exists():
            log.info("[VideoComposite] line %s: clip not on disk, skipping", line_id)
            continue
        # Prefer ledger dur_s if positive, else ffprobe, else fallback
        dur = ln.get("dur_s")
        if dur is None or float(dur) <= 0:
            dur = _ffprobe_dur(clip_path, ffprobe)
        if dur is None or float(dur) <= 0:
            dur = float(fallback_clip_length)
        timeline.append((clip_path, cumulative, float(dur)))
        cumulative += float(dur)
    return timeline


def _build_filter_graph(
    procgen_video: Path,
    timeline: list[tuple[Path, float, float]],
    canvas_w: int,
    canvas_h: int,
    canvas_fps: int,
    humo_h: int,
    blend_mode: str,
    blend_opacity: float,
    episode_dur: float,
) -> tuple[str, list[Path]]:
    """Build the ffmpeg -filter_complex string + ordered input list.

    Inputs (0-indexed):
        [0]  procgen video (base layer + audio source)
        [1..N] HuMo clips, one per timeline entry

    Filter graph (BUG-LOCAL-092 architecture):
        [0:v] fps -> scale -> setsar -> [procgen]
        [i:v] fps -> scale 624:humo_h -> setsar ->
              setpts (per-clip start_s) -> [hi]
        chain: [procgen] overlay each [hi] at x=offset_x,y=0 with
               enable='between(t,start,start+dur)'
        (optional) blend pass for `additive procgen-over-humo`
                    feel -- lower default opacity, screen mode by
                    default; opacity=0 disables the pass entirely.
        final: [...] -> [v]

    Why this order: procgen is the BASE (full opacity), HuMo
    overlays opaquely at the center pillarbox during each line's
    time window. The pillarbox sides ALWAYS show full procgen
    (the audio-reactive CRT visualizer Jeffrey wants), and the
    center swaps to HuMo only while a character is speaking.
    The previous order (black canvas + HuMo on top + blanket-
    blend procgen at addition@0.5) drowned everything in the
    procgen color cast (BUG-LOCAL-092 magenta/pink wash).
    """
    humo_w = round(humo_h * (480 / 832) / 8) * 8  # snap to mult of 8 (h264 chroma safe)
    offset_x = (canvas_w - humo_w) // 2

    parts = []
    # [0] procgen → time-aligned + scaled = BASE layer (sides + initial center)
    parts.append(
        f"[0:v]fps={canvas_fps},scale={canvas_w}:{canvas_h},setsar=1[procgen]"
    )
    # Per-clip scale + overlay chain. HuMo overlays directly on procgen.
    last_label = "procgen"
    inputs_list: list[Path] = [procgen_video]
    for idx, (clip_path, start_s, dur_s) in enumerate(timeline):
        in_idx = idx + 1
        inputs_list.append(clip_path)
        parts.append(
            f"[{in_idx}:v]fps={canvas_fps},scale={humo_w}:{humo_h},setsar=1,"
            f"setpts=PTS-STARTPTS+{start_s:.3f}/TB[h{idx}]"
        )
        new_label = f"s{idx}"
        end_s = start_s + dur_s
        parts.append(
            f"[{last_label}][h{idx}]overlay=x={offset_x}:y=0:"
            f"enable='between(t,{start_s:.3f},{end_s:.3f})'[{new_label}]"
        )
        last_label = new_label

    # Optional subtle procgen-over-HuMo "audio-reactive sheen" pass.
    # opacity=0 disables it entirely. Default is now low (0.0 in
    # widgets) so the composite is clean by default; users who want
    # the additive sheen can dial up blend_opacity in the widget.
    if blend_opacity and blend_opacity > 0:
        parts.append(
            f"[{last_label}][procgen]blend=all_mode={blend_mode}:"
            f"all_opacity={blend_opacity:.3f}[v]"
        )
    else:
        # Just rename the last overlay output to [v]
        parts.append(f"[{last_label}]copy[v]")
    return ";".join(parts), inputs_list


