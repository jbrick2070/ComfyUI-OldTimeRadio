def _make_gap_segment(
    image: Path,
    audio_source: Path,
    start_s: float,
    end_s: float,
    canvas_w: int,
    canvas_h: int,
    canvas_fps: int,
    out_path: Path,
    ffmpeg: str,
) -> Path:
    """Render a static-image mp4 covering [start_s, end_s] of the
    timeline. Image is letterboxed to canvas dimensions; audio is
    sliced from `audio_source` (typically the procgen mp4 carrying
    the master_mix track).

    Used to fill gap windows between HuMo dialogue clips in the
    humo_concat mode so the timeline has full visual + audio
    coverage. Falls back to silence if audio_source missing.
    """
    dur = max(0.0, end_s - start_s)
    if dur <= 0.0:
        raise ValueError(f"_make_gap_segment: non-positive duration {dur}")
    cmd = [
        ffmpeg, "-y", "-loglevel", "error",
        "-loop", "1", "-framerate", str(canvas_fps), "-i", str(image),
        "-ss", f"{start_s:.4f}", "-i", str(audio_source),
        "-vf", (
            f"scale={canvas_w}:{canvas_h}:force_original_aspect_ratio=decrease,"
            f"pad={canvas_w}:{canvas_h}:(ow-iw)/2:(oh-ih)/2:color=black,"
            f"fps={canvas_fps}"
        ),
        "-t", f"{dur:.4f}",
        "-c:v", "libx264", "-pix_fmt", "yuv420p", "-crf", "18", "-preset", "fast",
        "-c:a", "aac", "-b:a", "192k", "-ar", "48000",
        "-shortest",
        str(out_path),
    ]
    subprocess.run(cmd, check=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    return out_path


def _normalize_humo_segment(
    clip: Path,
    canvas_w: int,
    canvas_h: int,
    canvas_fps: int,
    humo_target_h: int,
    out_path: Path,
    ffmpeg: str,
) -> Path:
    """Pillarbox a HuMo clip into the canvas dimensions while
    PRESERVING its native audio (the source of mechanical lip-sync
    for the humo_concat mode). HuMo clips are 480x832 portrait;
    pillarbox to canvas_w x canvas_h with black side bars.
    """
    cmd = [
        ffmpeg, "-y", "-loglevel", "error",
        "-i", str(clip),
        "-vf", (
            f"scale=-2:{humo_target_h}:force_original_aspect_ratio=decrease,"
            f"pad={canvas_w}:{canvas_h}:(ow-iw)/2:(oh-ih)/2:color=black,"
            f"fps={canvas_fps}"
        ),
        "-c:v", "libx264", "-pix_fmt", "yuv420p", "-crf", "18", "-preset", "fast",
        # KEY: keep HuMo's native audio for perfect lip-sync.
        "-c:a", "aac", "-b:a", "192k", "-ar", "48000",
        str(out_path),
    ]
    subprocess.run(cmd, check=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    return out_path


def _resolve_bookend_image(
    ledger: dict,
    procgen: Path,
    fallback_dir: Path,
    ffmpeg: str,
) -> Path:
    """Locate the radio bookend image. Priority:
    1. ledger.radio_bookend_path (top-level field stamped by BatchFluxRender)
    2. ledger.meta.radio_bookend_path
    3. Fallback: extract first frame from procgen mp4
    """
    cand = ledger.get("radio_bookend_path") or ledger.get("meta", {}).get("radio_bookend_path")
    if cand:
        p = Path(cand)
        if p.exists():
            return p
        log.warning(
            "[VideoComposite] ledger.radio_bookend_path=%s does not exist; "
            "falling back to procgen frame",
            p,
        )
    fallback = fallback_dir / "bookend_fallback.png"
    if not fallback.exists():
        cmd = [
            ffmpeg, "-y", "-loglevel", "error",
            "-i", str(procgen), "-vframes", "1",
            str(fallback),
        ]
        subprocess.run(cmd, check=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
        log.info("[VideoComposite] bookend fallback: extracted %s", fallback)
    return fallback


def _pillarbox_humo_silent(
    clip: Path,
    canvas_w: int,
    canvas_h: int,
    canvas_fps: int,
    humo_target_h: int,
    out_path: Path,
    ffmpeg: str,
    extend_tail_s: float = 0.0,
) -> Path:
    """Pillarbox a HuMo clip into the canvas dimensions and STRIP
    its audio entirely (-an).  Video re-encodes via libx264; audio
    is dropped so the downstream mux step can attach the master mix
    audio with `-c:a copy` (no audio re-encode anywhere).

    Used by the master_mix_per_clip_mux mode (Step 6 of ROADMAP P0,
    2026-04-30 lock).  The whole point of this helper vs.
    `_normalize_humo_segment` is that this one drops the audio so
    the C7 byte-perfect path doesn't contaminate the master mix
    with a re-encoded HuMo native audio it'll discard anyway.

    ``extend_tail_s`` (2026-04-30 round-robin hardening, applied to
    the LAST clip in the timeline only): freeze-extend the final
    frame for this many seconds via ffmpeg's tpad filter.  This
    guarantees the silent_combined.mp4 ends slightly LATER than the
    master mix audio so the mux step's `-shortest` truncates an
    inaudible video tail rather than the trailing audio.  Without
    this, video frame quantization (40ms at 25fps) plus chunk
    rounding error can leave silent_combined a few frames short of
    the master mix duration -- and `-shortest` would then nuke the
    end of the audio, breaking C7 silently.  Adds zero re-encodes
    (tpad piggybacks the libx264 pass already happening here).
    """
    vf = (
        f"scale=-2:{humo_target_h}:force_original_aspect_ratio=decrease,"
        f"pad={canvas_w}:{canvas_h}:(ow-iw)/2:(oh-ih)/2:color=black,"
        f"fps={canvas_fps}"
    )
    if extend_tail_s > 0.0:
        # tpad with stop_mode=clone replays the last frame; cleaner
        # than introducing a second re-encode pass.  Append to the
        # filter chain so it runs after pillarbox.
        vf = f"{vf},tpad=stop_mode=clone:stop_duration={extend_tail_s:.3f}"
    cmd = [
        ffmpeg, "-y", "-loglevel", "error",
        "-i", str(clip),
        "-vf", vf,
        "-c:v", "libx264", "-pix_fmt", "yuv420p", "-crf", "18", "-preset", "fast",
        "-an",  # KEY: strip audio.  Master mix attaches at mux step.
        str(out_path),
    ]
    subprocess.run(cmd, check=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    return out_path


def _render_master_mix_per_clip_mux_mode(
    *,
    ledger: dict,
    clips_dir: Path,
    procgen: Path,
    out_mp4: Path,
    canvas_w: int,
    canvas_h: int,
    canvas_fps: int,
    humo_target_h: int,
    fallback_clip_length: float,
    ffmpeg: str,
    ffprobe: str,
) -> tuple[Path, list[str]]:
    """C7-byte-perfect mode (Step 6 of ROADMAP P0, 2026-04-30 lock).

    Pipeline:
      1. Sort ledger.lines[] by start_s; resolve each line's HuMo
         silent video on disk (clips_dir/<line_id>.mp4).
      2. For each line, pillarbox the HuMo clip to canvas dims with
         ``-an`` (strip audio).  Video gets one libx264 re-encode;
         audio is dropped entirely so it can't contaminate the
         master mix that attaches at step 4.
      3. concat-demuxer the pillarboxed silent clips with ``-c copy``
         (no video re-encode, no audio at all yet).
      4. Mux the silent combined video with the procgen master mix
         audio (single ffmpeg call, ``-c:v copy -c:a copy
         -shortest``).  Audio passes through with ZERO re-encodes.

    Total audio encodes vs. the existing ``humo_concat`` path:
      humo_concat: 3 ^^ AAC re-encodes (gap_segment + per-clip
                   normalize + final concat, lines 318/350/522).
      this mode:   0 audio re-encodes downstream of
                   SignalLostVideo's CreateVideo step.

    Returns (final_mp4_path, report_lines).  Raises on any
    unrecoverable subprocess failure so the caller can fall back to
    the legacy mode.

    Crossfade overlap regions (~500ms) between music_open and the
    first scene line, and the last scene line + music_close, are
    NOT crossfaded visually here -- the final concat is a hard cut.
    Adding a video crossfade would require re-encoding.  For
    SIGNAL LOST aesthetic, hard cuts on broadcast-distress
    transitions are acceptable; promote to filter-based crossfade
    if a future revision wants smoother seams.
    """
    report: list[str] = []
    t0 = time.time()

    # 1. Build timeline from ledger.lines[] (Step 4b/4c populated
    # speaker_role + start_s + dur_s for ALL audio events: dialogue,
    # announcer, sfx, music_open, music_close).  Walk lines instead
    # of clips so we honour the unified-coverage contract.
    #
    # BUG-LOCAL-129a (2026-05-01): when a line has no HuMo clip on
    # disk, fall back to a deterministic static-radio-still segment
    # rather than silently skipping. Closes the per-line audio/video
    # coverage gap that BUG-LOCAL-128 surfaced (sum(clip.dur_s) <
    # sum(line.dur_s) when HuMo can't / shouldn't render a line, e.g.
    # post-BUG-129b when announcer/music/sfx stop dispatching to HuMo
    # entirely). Still skips silently if no radio still is available.
    ledger_lines = ledger.get("lines") or []
    static_radio_png = _resolve_radio_still_for_static(ledger)
    static_seg_dir = out_mp4.parent / "_per_clip_mux_segments"
    timeline: list[dict] = []
    for ln in ledger_lines:
        line_id = str(ln.get("line_id") or "")
        if not line_id:
            continue
        start_s = ln.get("start_s")
        dur_s = ln.get("dur_s")
        if not isinstance(start_s, (int, float)) or not isinstance(dur_s, (int, float)):
            continue
        if dur_s <= 0:
            continue
        speaker_role = ln.get("speaker_role") or "character"
        clip_path = clips_dir / f"{line_id}.mp4"
        if clip_path.is_file():
            timeline.append({
                "line_id": line_id,
                "start_s": float(start_s),
                "dur_s": float(dur_s),
                "clip_path": clip_path,
                "speaker_role": speaker_role,
                "source_kind": "humo",
            })
            continue
        # Missing HuMo clip. Try static-radio fallback (BUG-129a).
        if static_radio_png is None:
            log.info(
                "[VideoComposite/per_clip_mux] skip %s: clip not on disk "
                "and no radio still available "
                "(speaker_role=%s start_s=%.3f dur_s=%.3f)",
                line_id, speaker_role, float(start_s), float(dur_s),
            )
            continue
        try:
            static_out = static_seg_dir / f"static_{line_id}.mp4"
            _render_static_radio_segment(
                radio_png=static_radio_png,
                dur_s=float(dur_s),
                canvas_w=canvas_w,
                canvas_h=canvas_h,
                canvas_fps=canvas_fps,
                out_path=static_out,
                ffmpeg=ffmpeg,
            )
        except subprocess.CalledProcessError as exc:
            stderr = exc.stderr.decode("utf-8", errors="replace") if exc.stderr else ""
            log.warning(
                "[VideoComposite/per_clip_mux] static-radio fallback for "
                "%s FAILED, skipping line: %s",
                line_id, stderr[:200],
            )
            continue
        log.info(
            "[VideoComposite/per_clip_mux] static-radio fill for %s "
            "(speaker_role=%s start_s=%.3f dur_s=%.3f) -> %s",
            line_id, speaker_role,
            float(start_s), float(dur_s), static_out.name,
        )
        timeline.append({
            "line_id": line_id,
            "start_s": float(start_s),
            "dur_s": float(dur_s),
            "clip_path": static_out,
            "speaker_role": speaker_role,
            "source_kind": "static_ffmpeg",
        })

    if not timeline:
        raise RuntimeError(
            "per_clip_mux: no usable HuMo clips for any line in "
            "ledger.lines[] (Step 6 requires Step 4b/4c-stamped roles "
            "and BatchHumoRender output for every audio event)"
        )

    timeline.sort(key=lambda x: x["start_s"])
    n_humo = sum(1 for e in timeline if e.get("source_kind") == "humo")
    n_static = sum(1 for e in timeline if e.get("source_kind") == "static_ffmpeg")
    report.append(
        f"per_clip_mux: timeline = {len(timeline)} clip(s) "
        f"({sum(1 for e in timeline if e['speaker_role']=='character')} char + "
        f"{sum(1 for e in timeline if e['speaker_role']=='announcer')} announcer + "
        f"{sum(1 for e in timeline if e['speaker_role']=='sfx')} sfx + "
        f"{sum(1 for e in timeline if e['speaker_role'] in ('music_open','music_close','music_inter'))} music) "
        f"[{n_humo} humo + {n_static} static]"
    )

    # 2. Pillarbox each HuMo clip to canvas dims and strip audio.
    # 2026-04-30 round-robin hardening: freeze-extend the surviving
    # LAST clip by 500 ms so silent_combined ends after the master
    # mix audio, so the mux step's `-shortest` truncates an inaudible
    # video tail rather than the trailing audio. Cumulative chunk-
    # rounding error across many clips can otherwise leave
    # silent_combined a few frames short, silently breaking C7 at
    # episode end.
    #
    # BUG-LOCAL-128 fix (2026-05-01): the previous policy padded
    # `idx == last_idx` where `last_idx = len(timeline) - 1` was
    # computed BEFORE the loop. If that clip failed pillarbox, the
    # surviving last clip got no tail pad and `-shortest` truncated
    # trailing audio. New policy: don't pad in the loop; re-pillarbox
    # the actual `pillarboxed[-1]` with tail pad after the loop. One
    # extra ffmpeg call when everything succeeds, correct behaviour
    # when the original last clip fails.
    _TAIL_PAD_S = 0.5
    seg_dir = out_mp4.parent / "_per_clip_mux_segments"
    seg_dir.mkdir(parents=True, exist_ok=True)
    pillarboxed: list[Path] = []
    pb_failures = 0
    for entry in timeline:
        seg_out = seg_dir / f"pb_{entry['line_id']}.mp4"
        try:
            _pillarbox_humo_silent(
                clip=entry["clip_path"],
                canvas_w=canvas_w, canvas_h=canvas_h,
                canvas_fps=canvas_fps, humo_target_h=humo_target_h,
                out_path=seg_out, ffmpeg=ffmpeg,
                extend_tail_s=0.0,
            )
            pillarboxed.append(seg_out)
        except subprocess.CalledProcessError as exc:
            stderr = exc.stderr.decode("utf-8", errors="replace") if exc.stderr else ""
            log.warning(
                "[VideoComposite/per_clip_mux] pillarbox %s failed: %s",
                entry["line_id"], stderr[:200],
            )
            report.append(
                f"  pillarbox {entry['line_id']}: FAILED ({stderr[:120]})"
            )
            pb_failures += 1

    if not pillarboxed:
        raise RuntimeError(
            "per_clip_mux: no segments survived pillarbox pass "
            "(check ffmpeg invocations + HuMo clip integrity)"
        )
    if pb_failures:
        report.append(
            f"per_clip_mux: WARNING {pb_failures} clip(s) lost during "
            f"pillarbox pass; proceeding with {len(pillarboxed)} survivors"
        )

    # 2b. BUG-LOCAL-128 fix: re-pillarbox the ACTUAL surviving last
    # clip with tail pad. Locate the timeline entry whose line_id
    # matches `pillarboxed[-1].stem` (stripped of "pb_" prefix), then
    # call _pillarbox_humo_silent again with extend_tail_s set. If
    # the re-pad call itself fails, log loudly and continue without
    # the pad -- the user gets a clear signal in the report and audio
    # may be tail-truncated but everything else still ships.
    surviving_last = pillarboxed[-1]
    surviving_line_id = surviving_last.stem
    if surviving_line_id.startswith("pb_"):
        surviving_line_id = surviving_line_id[3:]
    surviving_entry = next(
        (e for e in timeline if e["line_id"] == surviving_line_id),
        None,
    )
    if surviving_entry is None:
        log.warning(
            "[VideoComposite/per_clip_mux] could not locate timeline "
            "entry for surviving last clip %s; skipping tail pad",
            surviving_line_id,
        )
        report.append(
            f"  tail-pad: SKIPPED (no timeline match for {surviving_line_id})"
        )
    else:
        try:
            _pillarbox_humo_silent(
                clip=surviving_entry["clip_path"],
                canvas_w=canvas_w, canvas_h=canvas_h,
                canvas_fps=canvas_fps, humo_target_h=humo_target_h,
                out_path=surviving_last, ffmpeg=ffmpeg,
                extend_tail_s=_TAIL_PAD_S,
            )
            report.append(
                f"  tail-pad: +{_TAIL_PAD_S:.3f}s on {surviving_line_id} "
                f"(BUG-LOCAL-128 fix)"
            )
            log.info(
                "[VideoComposite/per_clip_mux] tail-pad +%.3fs on actual "
                "surviving last clip %s (BUG-LOCAL-128 fix)",
                _TAIL_PAD_S, surviving_line_id,
            )
        except subprocess.CalledProcessError as exc:
            stderr = exc.stderr.decode("utf-8", errors="replace") if exc.stderr else ""
            log.warning(
                "[VideoComposite/per_clip_mux] tail-pad on %s FAILED; "
                "trailing audio may be truncated by -shortest: %s",
                surviving_line_id, stderr[:200],
            )
            report.append(
                f"  tail-pad: FAILED on {surviving_line_id} "
                f"({stderr[:120]}) -- audio may truncate"
            )

    # 3. concat-demuxer the silent pillarboxed clips with -c copy.
    list_file = seg_dir / "concat.txt"
    list_file.write_text(
        "\n".join(f"file '{s.as_posix()}'" for s in pillarboxed),
        encoding="utf-8",
    )
    silent_combined = seg_dir / "silent_combined.mp4"
    cmd = [
        ffmpeg, "-y", "-loglevel", "warning",
        "-f", "concat", "-safe", "0",
        "-i", str(list_file),
        "-c", "copy",   # NO re-encode -- pillarbox already produced
                        # uniform H.264 yuv420p at canvas dims.
        str(silent_combined),
    ]
    subprocess.run(cmd, check=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    report.append(
        f"per_clip_mux: concat OK -> silent_combined {silent_combined.name}"
    )

    # 4. Mux silent_combined video + procgen master-mix audio with
    # -c copy throughout.  This is the C7-critical step: audio
    # passes through without re-encode.  -shortest trims any audio
    # overhang past the combined video length.
    cmd = [
        ffmpeg, "-y", "-loglevel", "warning",
        "-i", str(silent_combined),
        "-i", str(procgen),
        "-map", "0:v",   # video from concatenated HuMo
        "-map", "1:a",   # audio from procgen master mix
        "-c:v", "copy",
        "-c:a", "copy",
        "-shortest",
        str(out_mp4),
    ]
    subprocess.run(cmd, check=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE)

    elapsed = time.time() - t0
    report.append(
        f"per_clip_mux: assembled {out_mp4.name} in {elapsed:.1f}s "
        f"(audio passthrough, 0 re-encodes downstream of SignalLostVideo)"
    )
    return out_mp4, report


def _render_humo_concat_mode(
    *,
    ledger: dict,
    clips_dir: Path,
    procgen: Path,
    out_mp4: Path,
    canvas_w: int,
    canvas_h: int,
    canvas_fps: int,
    humo_target_h: int,
    fallback_clip_length: float,
    ffmpeg: str,
    ffprobe: str,
) -> tuple[Path, list[str]]:
    """Build the final mp4 in humo_concat mode.

    Pipeline:
      1. Sort ledger.clips[] by start_s, build (clip_path, start_s, dur_s)
         tuples honouring REAL master-mix timestamps (not cumulative).
      2. Resolve radio bookend image (or procgen-frame fallback).
      3. For each pair of adjacent clips with a gap between them,
         create a gap segment: bookend image + master_mix audio slice.
      4. For each HuMo clip, normalize to canvas dims keeping native
         audio (mechanical lip-sync guarantee).
      5. ffmpeg concat-demuxer joins all segments in time order.

    Returns (final_mp4_path, report_lines).
    """
    report: list[str] = []
    t0 = time.time()

    # 1. Build timeline from ledger.clips[] using real master-mix start_s
    ledger_clips = ledger.get("clips") or []
    timeline: list[tuple[Path, float, float]] = []
    for entry in ledger_clips:
        line_id = str(entry.get("line_id") or "")
        if not line_id:
            continue
        cp = Path(entry.get("mp4_path") or "")
        if not cp.exists():
            cp = clips_dir / f"{line_id}.mp4"
        if not cp.exists():
            log.info(
                "[VideoComposite/humo_concat] skip %s: clip not on disk",
                line_id,
            )
            continue
        start_s = float(entry.get("start_s") or 0.0)
        dur_s = float(entry.get("dur_s") or 0.0)
        if dur_s <= 0:
            dur_s = _ffprobe_dur(cp, ffprobe) or float(fallback_clip_length)
        timeline.append((cp, start_s, dur_s))
    if not timeline:
        raise RuntimeError("humo_concat: no usable HuMo clips in ledger.clips[]")
    timeline.sort(key=lambda t: t[1])

    # 2. Episode duration (from procgen so we cover trailing music)
    episode_dur = _ffprobe_dur(procgen, ffprobe) or (timeline[-1][1] + timeline[-1][2])
    report.append(
        f"humo_concat: {len(timeline)} HuMo clip(s), episode duration "
        f"{episode_dur:.2f}s"
    )

    # 3. Resolve bookend image
    seg_dir = out_mp4.parent / "_humo_concat_segments"
    seg_dir.mkdir(parents=True, exist_ok=True)
    bookend = _resolve_bookend_image(ledger, procgen, seg_dir, ffmpeg)
    report.append(f"humo_concat: bookend image = {bookend.name}")

    # 4. Build segment list (alternating gap, clip, gap, ...)
    segments: list[Path] = []
    cursor = 0.0
    for i, (clip_path, start_s, dur_s) in enumerate(timeline):
        if start_s - cursor > 0.05:  # 50ms tolerance for float drift
            gap_path = seg_dir / f"gap_{i:03d}.mp4"
            try:
                _make_gap_segment(
                    bookend, procgen, cursor, start_s,
                    canvas_w, canvas_h, canvas_fps,
                    gap_path, ffmpeg,
                )
                segments.append(gap_path)
            except Exception as exc:
                log.warning(
                    "[VideoComposite/humo_concat] gap[%d, %.2f-%.2f] failed: %s",
                    i, cursor, start_s, exc,
                )
        clip_seg = seg_dir / f"clip_{i:03d}.mp4"
        try:
            _normalize_humo_segment(
                clip_path, canvas_w, canvas_h, canvas_fps,
                humo_target_h, clip_seg, ffmpeg,
            )
            segments.append(clip_seg)
        except Exception as exc:
            log.warning(
                "[VideoComposite/humo_concat] clip[%d] %s normalize failed: %s",
                i, clip_path.name, exc,
            )
            continue
        cursor = start_s + dur_s
    # Trailing gap
    if cursor < episode_dur - 0.05:
        try:
            tail_seg = seg_dir / "gap_999.mp4"
            _make_gap_segment(
                bookend, procgen, cursor, episode_dur,
                canvas_w, canvas_h, canvas_fps,
                tail_seg, ffmpeg,
            )
            segments.append(tail_seg)
        except Exception as exc:
            log.warning(
                "[VideoComposite/humo_concat] trailing gap %.2f-%.2f failed: %s",
                cursor, episode_dur, exc,
            )

    if not segments:
        raise RuntimeError("humo_concat: no segments produced")
    report.append(f"humo_concat: {len(segments)} segment(s) ready for concat")

    # 5. Concat-demuxer assembly
    list_file = seg_dir / "concat.txt"
    list_file.write_text(
        "\n".join(f"file '{s.as_posix()}'" for s in segments),
        encoding="utf-8",
    )
    cmd = [
        ffmpeg, "-y", "-loglevel", "warning",
        "-f", "concat", "-safe", "0",
        "-i", str(list_file),
        "-c:v", "libx264", "-pix_fmt", "yuv420p", "-crf", "18", "-preset", "fast",
        "-c:a", "aac", "-b:a", "192k", "-ar", "48000",
        str(out_mp4),
    ]
    subprocess.run(cmd, check=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    elapsed = time.time() - t0
    report.append(
        f"humo_concat: assembled {out_mp4.name} in {elapsed:.1f}s"
    )
    return out_mp4, report


