def _resolve_episode_background(episode_dir: Path) -> Optional[Path]:
    """BUG-LOCAL-030 (2026-05-03 EVENING): pick a background image for the
    layered HuMo character composite.

    Priority:
      1. Freshest FLUX env still at ``<ep>/stills/full_env_*.png``
         (BUG-LOCAL-028 per-episode workspace layout).
      2. Radio bookend at ``<ep>/stills/radio_bookend_*.png`` (universal
         broadcast unit identity, always present per BUG-028 fix).
      3. None -- caller falls back to plain canvas-fill on black.

    Phase A uses the freshest env still as the universal HuMo backdrop
    (one background per episode). Phase B follow-up could add per-scene
    env still selection via ``ledger.lines[].shot_id`` -> scenes mapping.
    """
    stills = episode_dir / "stills"
    if not stills.is_dir():
        return None
    env_pngs = sorted(
        stills.glob("full_env_*.png"),
        key=lambda p: p.stat().st_mtime,
        reverse=True,
    )
    if env_pngs:
        return env_pngs[0]
    radio_bookends = sorted(
        stills.glob("radio_bookend_*.png"),
        key=lambda p: p.stat().st_mtime,
        reverse=True,
    )
    if radio_bookends:
        return radio_bookends[0]
    return None


def _layered_per_clip_silent(
    clip: Path,
    speaker_role: str,
    canvas_w: int,
    canvas_h: int,
    canvas_fps: int,
    humo_pillar_w: int,
    humo_pillar_h: int,
    background_png: Optional[Path],
    out_path: Path,
    ffmpeg: str,
    extend_tail_s: float = 0.0,
    truncate_to_s: Optional[float] = None,
) -> Path:
    """BUG-LOCAL-030 layered per-clip composite (1472x832 canvas, 2026-05-03
    EVENING Jeffrey final spec).

    Two render paths chosen by ``speaker_role``:

    - ``speaker_role == "character"`` AND ``background_png`` exists:
        LAYERED composite. Background = ``background_png`` scaled-cropped
        to fill the canvas. Pillar = HuMo clip scaled to canvas height
        (preserving aspect), center-cropped to ``humo_pillar_w x
        humo_pillar_h``. Pillar overlaid centered on background. Output
        = full canvas with character lipsync on a stable scene backdrop.

    - any other ``speaker_role`` (announcer / sfx / music_*) OR
      ``background_png`` is None:
        SINGLE-SOURCE fill. Clip scaled-cropped to fill the canvas. This
        handles LTX clips (1216x704 -> 1472x832 fill, ~1.21x scale up
        with thin side bars per the BUG-030 math) and the no-background
        fallback for HuMo when no env still exists yet.

    Drops audio entirely (-an) in both paths -- master mix audio attaches
    at the final mux step downstream so C7 byte-identity holds.

    ``extend_tail_s``: BUG-LOCAL-128 tail-pad (preserves trailing audio
    against ``-shortest`` truncation in the final mux). Appended to the
    end of either filter chain via ``tpad=stop_mode=clone``.
    """
    is_layered = (
        speaker_role == "character"
        and background_png is not None
        and background_png.exists()
    )

    if is_layered:
        bg_chain = (
            f"[1:v]scale={canvas_w}:{canvas_h}:force_original_aspect_ratio=increase,"
            f"crop={canvas_w}:{canvas_h},fps={canvas_fps}[bg]"
        )
        pillar_chain = (
            f"[0:v]scale=-2:{humo_pillar_h}:force_original_aspect_ratio=decrease,"
            f"crop={humo_pillar_w}:{humo_pillar_h},fps={canvas_fps}[pillar]"
        )
        # BUG-LOCAL-030 hardening: even-snap overlay X for yuv420p chroma
        # alignment (same Gemini round-robin catch as the simple-pillarbox
        # pad fix). Pillar 512 in canvas 1472 gives 480 (already even),
        # but a future widget tweak (e.g. humo_pillar_width=510) would
        # otherwise crash. Defensive.
        overlay_chain = "[bg][pillar]overlay=x=trunc((W-w)/4)*2:y=0[v]"
        if extend_tail_s > 0.0:
            overlay_chain = (
                "[bg][pillar]overlay=x=trunc((W-w)/4)*2:y=0,"
                f"tpad=stop_mode=clone:stop_duration={extend_tail_s:.3f}[v]"
            )
        filter_complex = f"{bg_chain};{pillar_chain};{overlay_chain}"
        cmd = [
            ffmpeg, "-y", "-loglevel", "error",
            "-i", str(clip),
            "-loop", "1", "-framerate", str(canvas_fps), "-i", str(background_png),
            "-filter_complex", filter_complex,
            "-map", "[v]",
            "-c:v", "libx264", "-pix_fmt", "yuv420p", "-crf", "18", "-preset", "fast",
            # BUG-LOCAL-117d hardening 2026-05-07: lock timebase to match
            # _save_video_mp4 + boomerang + static fill so concat-demuxer
            # with -c copy in step 3 (silent_combined.mp4) doesn't drift
            # across seams.
            "-video_track_timescale", _STATIC_SEGMENT_TIMEBASE,
            "-an",
        ]
        # BUG-LOCAL-031 Track 1 (per-clip duration matching): if the
        # video clip is LONGER than the audio target, truncate via -t.
        # Pad-extend cases are handled by the `extend_tail_s` path
        # above (tpad inside the filter chain).
        if truncate_to_s is not None and truncate_to_s > 0.0:
            cmd.extend(["-t", f"{float(truncate_to_s):.3f}"])
        cmd.append(str(out_path))
    else:
        # BUG-LOCAL-030 revised spec (2026-05-03 EVENING): scale-FIT
        # (preserve aspect ratio, no crop) + pad with black to canvas
        # dims. Per Jeffrey: "humo native portrait render then native
        # scaled to 1472x832 (black pillaboxes)" -- HuMo content stays
        # at native quality, surrounding void is BLACK BARS, and the
        # post-RTXUpscale procgen blend (Phase B) fills those bars
        # with audio-reactive CRT scanlines. LTX native landscape
        # (832x480) gets scale-fit too: scale to height=832 = 1442x832,
        # pad to 1472x832 = ~15px black per side (effectively full
        # canvas with hairline bars).
        #
        # BUG-LOCAL-030 hardening (2026-05-03 EVENING, post-round-robin
        # Gemini catch): pad offsets MUST be EVEN for yuv420p chroma
        # alignment. The naive `(ow-iw)/2` produces 15 for LTX (odd!)
        # which fails on older ffmpeg builds with "x and y must be even
        # in yuv420p" and may produce subtle chroma asymmetry on newer
        # builds that auto-snap with warning. The `trunc((ow-iw)/4)*2`
        # form forces the offset to the largest even integer <=
        # (ow-iw)/2 (15 -> 14, 496 -> 496, 0 -> 0). Slightly off-center
        # by at most 1 pixel for asymmetric pads -- imperceptible.
        vf = (
            f"scale=-2:{canvas_h}:force_original_aspect_ratio=decrease,"
            f"pad={canvas_w}:{canvas_h}:"
            f"trunc((ow-iw)/4)*2:trunc((oh-ih)/4)*2:color=black,"
            f"fps={canvas_fps}"
        )
        if extend_tail_s > 0.0:
            vf = f"{vf},tpad=stop_mode=clone:stop_duration={extend_tail_s:.3f}"
        cmd = [
            ffmpeg, "-y", "-loglevel", "error",
            "-i", str(clip),
            "-vf", vf,
            "-c:v", "libx264", "-pix_fmt", "yuv420p", "-crf", "18", "-preset", "fast",
            # BUG-LOCAL-117d hardening 2026-05-07: timebase contract.
            "-video_track_timescale", _STATIC_SEGMENT_TIMEBASE,
            "-an",
        ]
        # BUG-LOCAL-031 Track 1: truncate path (see comment in layered branch).
        if truncate_to_s is not None and truncate_to_s > 0.0:
            cmd.extend(["-t", f"{float(truncate_to_s):.3f}"])
        cmd.append(str(out_path))

    subprocess.run(cmd, check=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    return out_path


def _pillarbox_humo_silent(
    clip: Path,
    canvas_w: int,
    canvas_h: int,
    canvas_fps: int,
    humo_target_h: int,
    out_path: Path,
    ffmpeg: str,
    extend_tail_s: float = 0.0,
) -> Path:
    """Pillarbox a HuMo clip into the canvas dimensions and STRIP
    its audio entirely (-an).  Video re-encodes via libx264; audio
    is dropped so the downstream mux step can attach the master mix
    audio with `-c:a copy` (no audio re-encode anywhere).

    Used by the master_mix_per_clip_mux mode (Step 6 of ROADMAP P0,
    2026-04-30 lock).  The whole point of this helper vs.
    `_normalize_humo_segment` is that this one drops the audio so
    the C7 byte-perfect path doesn't contaminate the master mix
    with a re-encoded HuMo native audio it'll discard anyway.

    ``extend_tail_s`` (2026-04-30 round-robin hardening, applied to
    the LAST clip in the timeline only): freeze-extend the final
    frame for this many seconds via ffmpeg's tpad filter.  This
    guarantees the silent_combined.mp4 ends slightly LATER than the
    master mix audio so the mux step's `-shortest` truncates an
    inaudible video tail rather than the trailing audio.  Without
    this, video frame quantization (40ms at 25fps) plus chunk
    rounding error can leave silent_combined a few frames short of
    the master mix duration -- and `-shortest` would then nuke the
    end of the audio, breaking C7 silently.  Adds zero re-encodes
    (tpad piggybacks the libx264 pass already happening here).
    """
    vf = (
        f"scale=-2:{humo_target_h}:force_original_aspect_ratio=decrease,"
        f"pad={canvas_w}:{canvas_h}:(ow-iw)/2:(oh-ih)/2:color=black,"
        f"fps={canvas_fps}"
    )
    if extend_tail_s > 0.0:
        # tpad with stop_mode=clone replays the last frame; cleaner
        # than introducing a second re-encode pass.  Append to the
        # filter chain so it runs after pillarbox.
        vf = f"{vf},tpad=stop_mode=clone:stop_duration={extend_tail_s:.3f}"
    cmd = [
        ffmpeg, "-y", "-loglevel", "error",
        "-i", str(clip),
        "-vf", vf,
        "-c:v", "libx264", "-pix_fmt", "yuv420p", "-crf", "18", "-preset", "fast",
        # BUG-LOCAL-117d hardening 2026-05-07: timebase contract so
        # concat-demuxer with -c copy doesn't drift at HuMo<->LTX seams.
        "-video_track_timescale", _STATIC_SEGMENT_TIMEBASE,
        "-an",  # KEY: strip audio.  Master mix attaches at mux step.
        str(out_path),
    ]
    subprocess.run(cmd, check=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    return out_path


def _render_master_mix_per_clip_mux_mode(
    *,
    ledger: dict,
    clips_dir: Path,
    procgen: Path,
    out_mp4: Path,
    canvas_w: int,
    canvas_h: int,
    canvas_fps: int,
    humo_target_h: int,
    fallback_clip_length: float,
    ffmpeg: str,
    ffprobe: str,
    humo_pillar_w: int = 512,
) -> tuple[Path, list[str]]:
    """C7-byte-perfect mode (Step 6 of ROADMAP P0, 2026-04-30 lock).

    Pipeline:
      1. Sort ledger.lines[] by start_s; resolve each line's HuMo
         silent video on disk (clips_dir/<line_id>.mp4).
      2. For each line, pillarbox the HuMo clip to canvas dims with
         ``-an`` (strip audio).  Video gets one libx264 re-encode;
         audio is dropped entirely so it can't contaminate the
         master mix that attaches at step 4.
      3. concat-demuxer the pillarboxed silent clips with ``-c copy``
         (no video re-encode, no audio at all yet).
      4. Mux the silent combined video with the procgen master mix
         audio (single ffmpeg call, ``-c:v copy -c:a copy
         -shortest``).  Audio passes through with ZERO re-encodes.

    Total audio encodes vs. the existing ``humo_concat`` path:
      humo_concat: 3 ^^ AAC re-encodes (gap_segment + per-clip
                   normalize + final concat, lines 318/350/522).
      this mode:   0 audio re-encodes downstream of
                   SignalLostVideo's CreateVideo step.

    Returns (final_mp4_path, report_lines).  Raises on any
    unrecoverable subprocess failure so the caller can fall back to
    the legacy mode.

    Crossfade overlap regions (~500ms) between music_open and the
    first scene line, and the last scene line + music_close, are
    NOT crossfaded visually here -- the final concat is a hard cut.
    Adding a video crossfade would require re-encoding.  For
    SIGNAL LOST aesthetic, hard cuts on broadcast-distress
    transitions are acceptable; promote to filter-based crossfade
    if a future revision wants smoother seams.
    """
    report: list[str] = []
    t0 = time.time()

    # BUG-LOCAL-030 long-form hardening (2026-05-03 EVENING, post
    # round-robin risk-#10 review): phase barrier handoff from upstream
    # generation (BatchHumo / BatchLTX / Bark / MusicGen / AudioGen).
    # PyTorch is lazy about returning RAM/VRAM after heavy generation;
    # nudge it before the composite phase starts piping ~100 ffmpeg
    # subprocesses. DRAM canary is best-effort -- if it trips we LOG
    # the warning into the report but continue (composite is mostly
    # ffmpeg subprocess work; in-process Python heap is small).
    try:
        from . import _otr_memory as _OTRM  # type: ignore
        _OTRM.phase_gc("VideoComposite/per_clip_mux entry")
        _ok, _reason = _OTRM.dram_canary(label="VideoComposite/per_clip_mux entry")
        if not _ok:
            report.append(f"per_clip_mux: DRAM canary WARNING -- {_reason}")
    except Exception as _exc:
        log.warning(
            "[VideoComposite/per_clip_mux] memory hygiene helper "
            "unavailable (%s); proceeding", _exc,
        )

    # 1. Build timeline from ledger.lines[] (Step 4b/4c populated
    # speaker_role + start_s + dur_s for ALL audio events: dialogue,
    # announcer, sfx, music_open, music_close).  Walk lines instead
    # of clips so we honour the unified-coverage contract.
    #
    # BUG-LOCAL-129a (2026-05-01): when a line has no HuMo clip on
    # disk, fall back to a deterministic static-radio-still segment
    # rather than silently skipping. Closes the per-line audio/video
    # coverage gap that BUG-LOCAL-128 surfaced (sum(clip.dur_s) <
    # sum(line.dur_s) when HuMo can't / shouldn't render a line, e.g.
    # post-BUG-129b when announcer/music/sfx stop dispatching to HuMo
    # entirely). Still skips silently if no radio still is available.
    ledger_lines = ledger.get("lines") or []
    static_radio_png = _resolve_radio_still_for_static(ledger)
    static_seg_dir = out_mp4.parent / "_per_clip_mux_segments"
    # BUG-LOCAL-135 (2026-05-08): resolve a canonical motion loop for
    # music / sfx / gap fills so the radio set keeps subtle motion
    # across the full episode instead of N seconds of dead-frozen
    # frames. Lookup is read-only; if it returns None every fill site
    # below falls through to BUG-LOCAL-129a static-radio behavior with
    # zero behavioral change. clips_dir is the per-episode HuMo output
    # dir (BatchHumoRender); episode_dir is its parent.
    try:
        loop_motion_mp4 = _resolve_loop_motion_for_fill(
            ledger=ledger,
            clips_dir=clips_dir,
            episode_dir=clips_dir.parent,
        )
    except Exception as exc:
        log.warning(
            "[VideoComposite/per_clip_mux] BUG-135 loop resolver raised; "
            "falling back to static-only fill: %s",
            exc,
        )
        loop_motion_mp4 = None
    if loop_motion_mp4 is not None:
        log.info(
            "[VideoComposite/per_clip_mux] BUG-135 motion-loop fill ENABLED: "
            "loop=%s (music/sfx/gap segments will ffmpeg-loop this clip "
            "instead of painting BUG-129a static-radio frames)",
            loop_motion_mp4.name,
        )
    else:
        log.info(
            "[VideoComposite/per_clip_mux] BUG-135 motion-loop fill UNAVAILABLE "
            "(no LTX clip on disk yet); using BUG-129a static-radio fill "
            "for this run"
        )
    timeline: list[dict] = []
    for ln in ledger_lines:
        line_id = str(ln.get("line_id") or "")
        if not line_id:
            continue
        start_s = ln.get("start_s")
        dur_s = ln.get("dur_s")
        if not isinstance(start_s, (int, float)) or not isinstance(dur_s, (int, float)):
            continue
        if dur_s <= 0:
            continue
        speaker_role = ln.get("speaker_role") or "character"
        clip_path = clips_dir / f"{line_id}.mp4"
        if clip_path.is_file():
            timeline.append({
                "line_id": line_id,
                "start_s": float(start_s),
                "dur_s": float(dur_s),
                "clip_path": clip_path,
                "speaker_role": speaker_role,
                "source_kind": "humo",
            })
            continue
        # Missing HuMo clip. Prefer BUG-LOCAL-135 motion-loop fill;
        # fall back to BUG-LOCAL-129a static-radio fill on resolver
        # miss or ffmpeg failure.
        fill_source_kind = None  # "loop_ffmpeg" or "static_ffmpeg"
        fill_out: "Path | None" = None
        if loop_motion_mp4 is not None:
            try:
                loop_out = static_seg_dir / f"loop_{line_id}.mp4"
                _render_loop_motion_segment(
                    loop_mp4=loop_motion_mp4,
                    dur_s=float(dur_s),
                    canvas_w=canvas_w,
                    canvas_h=canvas_h,
                    canvas_fps=canvas_fps,
                    out_path=loop_out,
                    ffmpeg=ffmpeg,
                )
                fill_out = loop_out
                fill_source_kind = "loop_ffmpeg"
            except subprocess.CalledProcessError as exc:
                stderr = exc.stderr.decode("utf-8", errors="replace") if exc.stderr else ""
                log.warning(
                    "[VideoComposite/per_clip_mux] BUG-135 motion-loop fill "
                    "for %s FAILED, falling through to static-radio: %s",
                    line_id, stderr[:200],
                )
        if fill_out is None:
            if static_radio_png is None:
                log.info(
                    "[VideoComposite/per_clip_mux] skip %s: clip not on disk "
                    "and no radio still available "
                    "(speaker_role=%s start_s=%.3f dur_s=%.3f)",
                    line_id, speaker_role, float(start_s), float(dur_s),
                )
                continue
            try:
                static_out = static_seg_dir / f"static_{line_id}.mp4"
                _render_static_radio_segment(
                    radio_png=static_radio_png,
                    dur_s=float(dur_s),
                    canvas_w=canvas_w,
                    canvas_h=canvas_h,
                    canvas_fps=canvas_fps,
                    out_path=static_out,
                    ffmpeg=ffmpeg,
                )
                fill_out = static_out
                fill_source_kind = "static_ffmpeg"
            except subprocess.CalledProcessError as exc:
                stderr = exc.stderr.decode("utf-8", errors="replace") if exc.stderr else ""
                log.warning(
                    "[VideoComposite/per_clip_mux] static-radio fallback for "
                    "%s FAILED, skipping line: %s",
                    line_id, stderr[:200],
                )
                continue
        log.info(
            "[VideoComposite/per_clip_mux] %s fill for %s "
            "(speaker_role=%s start_s=%.3f dur_s=%.3f) -> %s",
            fill_source_kind, line_id, speaker_role,
            float(start_s), float(dur_s), fill_out.name,
        )
        timeline.append({
            "line_id": line_id,
            "start_s": float(start_s),
            "dur_s": float(dur_s),
            "clip_path": fill_out,
            "speaker_role": speaker_role,
            "source_kind": fill_source_kind,
        })

    if not timeline:
        raise RuntimeError(
            "per_clip_mux: no usable HuMo clips for any line in "
            "ledger.lines[] (Step 6 requires Step 4b/4c-stamped roles "
            "and BatchHumoRender output for every audio event)"
        )

    timeline.sort(key=lambda x: x["start_s"])

    # BUG-LOCAL-084 (2026-05-04 LATE): insert static-radio gap-fill entries
    # so the per-clip concat covers the FULL master-audio timeline, not just
    # the dialogue islands.  Without this pass:
    #   - 0..first_clip.start_s pre-roll music plays with NO video coverage
    #     (composite starts immediately with first dialogue clip; audio leads
    #      video by N seconds; cumulative drift makes wrong-mouth-on-wrong-voice)
    #   - inter-clip silences (~0.1-2s between adjacent lines) play with no
    #     video coverage; same drift mechanism, smaller magnitude
    #   - last_clip.end..episode_dur tail music plays with no video coverage;
    #     -shortest then truncates the trailing audio (breaks C7)
    # Fix: walk the sorted timeline by start_s and insert a static-radio
    # segment for any gap > GAP_TOL_S, plus a trailing fill to the end of the
    # master audio.  Reuses the same _render_static_radio_segment helper that
    # BUG-LOCAL-129a uses for missing-clip cases.
    GAP_TOL_S = 0.1  # ignore sub-frame gaps; not worth the segment-overhead

    def _render_gap_segment(
        *, dur_s: float, out_path: Path,
    ) -> "tuple[Path | None, str | None]":
        """BUG-LOCAL-135 (2026-05-08): inner helper for BUG-084 gap-fill.
        Tries motion-loop fill first; falls back to static-radio fill;
        returns (path, source_kind) on success or (None, None) on
        complete failure. Caller decides whether to log/skip.
        """
        if loop_motion_mp4 is not None:
            try:
                _render_loop_motion_segment(
                    loop_mp4=loop_motion_mp4,
                    dur_s=dur_s,
                    canvas_w=canvas_w,
                    canvas_h=canvas_h,
                    canvas_fps=canvas_fps,
                    out_path=out_path,
                    ffmpeg=ffmpeg,
                )
                return out_path, "loop_gapfill"
            except subprocess.CalledProcessError as exc:
                stderr = exc.stderr.decode("utf-8", errors="replace") if exc.stderr else ""
                log.warning(
                    "[VideoComposite/per_clip_mux] BUG-135 motion-loop gap-fill "
                    "dur=%.3f FAILED, falling through to static: %s",
                    dur_s, stderr[:200],
                )
        if static_radio_png is None:
            return None, None
        try:
            _render_static_radio_segment(
                radio_png=static_radio_png,
                dur_s=dur_s,
                canvas_w=canvas_w,
                canvas_h=canvas_h,
                canvas_fps=canvas_fps,
                out_path=out_path,
                ffmpeg=ffmpeg,
            )
            return out_path, "static_gapfill"
        except subprocess.CalledProcessError as exc:
            stderr = exc.stderr.decode("utf-8", errors="replace") if exc.stderr else ""
            log.warning(
                "[VideoComposite/per_clip_mux] BUG-084 static gap-fill "
                "dur=%.3f FAILED: %s",
                dur_s, stderr[:200],
            )
            return None, None

    if (loop_motion_mp4 is not None) or (static_radio_png is not None):
        try:
            episode_dur = _ffprobe_dur(procgen, ffprobe) or 0.0
        except Exception:
            episode_dur = 0.0
        gapfilled: list[dict] = []
        cursor = 0.0
        gap_count = 0
        gap_total_s = 0.0
        loop_count = 0
        static_count = 0
        for entry in timeline:
            entry_start = float(entry["start_s"])
            gap_s = entry_start - cursor
            if gap_s > GAP_TOL_S:
                gap_id = f"gap_{cursor:08.3f}"
                # Pick filename prefix per fill kind so the segment
                # provenance is visible from disk later (loop_*.mp4
                # vs static_*.mp4 in _per_clip_mux_segments/).
                loop_path = static_seg_dir / f"loop_{gap_id}.mp4"
                static_path = static_seg_dir / f"static_{gap_id}.mp4"
                # Try loop first (writes loop_*.mp4); if that fails the
                # helper retries static (writes static_*.mp4 itself).
                fill_path, fill_kind = _render_gap_segment(
                    dur_s=gap_s,
                    out_path=loop_path if loop_motion_mp4 is not None else static_path,
                )
                if fill_path is not None:
                    gapfilled.append({
                        "line_id": gap_id,
                        "start_s": cursor,
                        "dur_s": gap_s,
                        "clip_path": fill_path,
                        "speaker_role": "gap_fill",
                        "source_kind": fill_kind,
                    })
                    gap_count += 1
                    gap_total_s += gap_s
                    if fill_kind == "loop_gapfill":
                        loop_count += 1
                    else:
                        static_count += 1
            gapfilled.append(entry)
            cursor = entry_start + float(entry["dur_s"])
        # Trailing tail-fill: from last clip's end to the end of master audio
        if episode_dur > 0.0:
            tail_gap = episode_dur - cursor
            if tail_gap > GAP_TOL_S:
                tail_id = f"gap_tail_{cursor:08.3f}"
                loop_tail_path = static_seg_dir / f"loop_{tail_id}.mp4"
                static_tail_path = static_seg_dir / f"static_{tail_id}.mp4"
                fill_path, fill_kind = _render_gap_segment(
                    dur_s=tail_gap,
                    out_path=loop_tail_path if loop_motion_mp4 is not None else static_tail_path,
                )
                if fill_path is not None:
                    gapfilled.append({
                        "line_id": tail_id,
                        "start_s": cursor,
                        "dur_s": tail_gap,
                        "clip_path": fill_path,
                        "speaker_role": "gap_fill",
                        "source_kind": fill_kind,
                    })
                    gap_count += 1
                    gap_total_s += tail_gap
                    cursor = episode_dur
                    if fill_kind == "loop_gapfill":
                        loop_count += 1
                    else:
                        static_count += 1
        timeline = gapfilled
        if gap_count > 0:
            log.info(
                "[VideoComposite/per_clip_mux] BUG-084 gap-fill: inserted "
                "%d segment(s) total %.3f s (loop=%d static=%d)",
                gap_count, gap_total_s, loop_count, static_count,
            )
            report.append(
                f"per_clip_mux: BUG-LOCAL-084 gap-fill -- "
                f"{gap_count} segment(s), +{gap_total_s:.2f}s coverage "
                f"(loop={loop_count} static={static_count})"
            )
    else:
        log.warning(
            "[VideoComposite/per_clip_mux] BUG-084: NO static_radio_png "
            "available; cannot fill timeline gaps. Audio will lead video "
            "by the cumulative gap duration. Resolve a radio_bookend_*.png "
            "in stills/ or ledger.meta.paths.radio_bookend_path."
        )

    n_humo = sum(1 for e in timeline if e.get("source_kind") == "humo")
    n_static = sum(1 for e in timeline if e.get("source_kind") == "static_ffmpeg")
    n_gap = sum(1 for e in timeline if e.get("source_kind") == "static_gapfill")
    report.append(
        f"per_clip_mux: timeline = {len(timeline)} clip(s) "
        f"({sum(1 for e in timeline if e['speaker_role']=='character')} char + "
        f"{sum(1 for e in timeline if e['speaker_role']=='announcer')} announcer + "
        f"{sum(1 for e in timeline if e['speaker_role']=='sfx')} sfx + "
        f"{sum(1 for e in timeline if e['speaker_role'] in ('music_open','music_close','music_inter'))} music + "
        f"{n_gap} gap_fill) "
        f"[{n_humo} humo + {n_static} static + {n_gap} gapfill]"
    )

    # 2. Pillarbox each HuMo clip to canvas dims and strip audio.
    # 2026-04-30 round-robin hardening: freeze-extend the surviving
    # LAST clip by 500 ms so silent_combined ends after the master
    # mix audio, so the mux step's `-shortest` truncates an inaudible
    # video tail rather than the trailing audio. Cumulative chunk-
    # rounding error across many clips can otherwise leave
    # silent_combined a few frames short, silently breaking C7 at
    # episode end.
    #
    # BUG-LOCAL-128 fix (2026-05-01): the previous policy padded
    # `idx == last_idx` where `last_idx = len(timeline) - 1` was
    # computed BEFORE the loop. If that clip failed pillarbox, the
    # surviving last clip got no tail pad and `-shortest` truncated
    # trailing audio. New policy: don't pad in the loop; re-pillarbox
    # the actual `pillarboxed[-1]` with tail pad after the loop. One
    # extra ffmpeg call when everything succeeds, correct behaviour
    # when the original last clip fails.
    _TAIL_PAD_S = 0.5
    seg_dir = out_mp4.parent / "_per_clip_mux_segments"
    seg_dir.mkdir(parents=True, exist_ok=True)

    # BUG-LOCAL-030 revised spec (2026-05-03 EVENING): NO env-still
    # backdrop in this Phase. Per Jeffrey's revised wording -- "humo
    # native portrait render then native scaled to 1472x832 (black
    # pillaboxes)" -- HuMo character clips render with BLACK bars on
    # each side, NOT layered onto a FLUX env still. The post-RTXUpscale
    # procgen blend (Phase B, separate commit) fills those black bars
    # with audio-reactive CRT scanlines so the visible black surround
    # becomes part of the SIGNAL LOST visual signature instead of
    # boring void.
    #
    # The ``_resolve_episode_background`` helper + ``_layered_per_clip_silent``
    # layered branch are kept in the codebase (with their own tests) for
    # future use cases where a static backdrop layer IS desired -- but
    # the current Phase A renderer always passes ``background_png=None``
    # so the layered helper falls into its scale-fit + pad-with-black
    # branch.
    background_png = None
    log.info(
        "[VideoComposite/per_clip_mux] BUG-030 simple-pillarbox mode: "
        "HuMo + LTX clips scale-fit into 1472x832 with black pillarbox "
        "bars; procgen visual fill is Phase B (post-RTXUpscale blend)"
    )
    report.append(
        "per_clip_mux: simple-pillarbox mode (HuMo native + black bars)"
    )

    # BUG-LOCAL-031 Track 1 (per-clip duration matching, 2026-05-03 EVENING):
    # Audio per line varies (Bark / Kokoro emit 8-14 s per dialogue line).
    # Video per clip is FIXED to HuMo's max-frame cap (~6.88 s for character
    # lines) and LTX's actual output (~7.72 s for announcer lines, even
    # though ledger.clips[].dur_s lies and reports the LINE'S audio dur
    # for LTX -- BUG-LOCAL-033). The naive concat thus drifts the video
    # ahead of the audio by ~26 s over a 50 s episode (proven via
    # ffprobe drift audit 2026-05-03 EVENING).
    #
    # Fix: ffprobe each clip's ACTUAL on-disk dur, compare to the audio
    # target from ledger.lines[].dur_s (which IS correct), and per-clip:
    #   gap > +tol -> tpad freeze-extend by gap seconds (clone last frame)
    #   gap < -tol -> -t truncate to audio_target seconds
    #   |gap| <= tol -> no-op
    # The LAST clip's BUG-LOCAL-128 tail-pad (+0.5s for -shortest safety)
    # is layered on top of the duration-match extension below in step 2b.
    #
    # Rule (BUG-LOCAL-033): metadata describes intent, ffprobe describes
    # reality. NEVER trust ledger.clips[].dur_s; always probe.
    try:
        from . import _otr_probe as _PROBE  # type: ignore
    except Exception:
        _PROBE = None  # type: ignore

    pillarboxed: list[Path] = []
    pb_failures = 0
    sync_ext_total = 0.0
    sync_trunc_total = 0.0
    for entry in timeline:
        seg_out = seg_dir / f"pb_{entry['line_id']}.mp4"
        # Per-clip duration match: probe the SOURCE clip on disk and
        # compute the gap vs the audio target.
        _audio_target = float(entry.get("dur_s") or 0.0)
        _video_actual = (
            _PROBE.probe_duration_s(entry["clip_path"], ffprobe=ffprobe)
            if _PROBE is not None else 0.0
        )
        _extend_s = 0.0
        _truncate_s: float | None = None
        if _PROBE is not None and _video_actual > 0.0 and _audio_target > 0.0:
            _gap, _action = _PROBE.duration_gap_s(_audio_target, _video_actual)
            if _action == "extend":
                _extend_s = _gap
                sync_ext_total += _gap
                report.append(
                    f"  sync {entry['line_id']}: video {_video_actual:.3f}s -> "
                    f"audio {_audio_target:.3f}s (extend +{_gap:.3f}s)"
                )
            elif _action == "truncate":
                _truncate_s = _audio_target
                sync_trunc_total += -_gap
                report.append(
                    f"  sync {entry['line_id']}: video {_video_actual:.3f}s -> "
                    f"audio {_audio_target:.3f}s (truncate -{-_gap:.3f}s)"
                )
        try:
            _layered_per_clip_silent(
                clip=entry["clip_path"],
                speaker_role=entry.get("speaker_role", ""),
                canvas_w=canvas_w, canvas_h=canvas_h,
                canvas_fps=canvas_fps,
                humo_pillar_w=humo_pillar_w,
                humo_pillar_h=humo_target_h,
                background_png=background_png,
                out_path=seg_out, ffmpeg=ffmpeg,
                extend_tail_s=_extend_s,
                truncate_to_s=_truncate_s,
            )
            pillarboxed.append(seg_out)
        except subprocess.CalledProcessError as exc:
            stderr = exc.stderr.decode("utf-8", errors="replace") if exc.stderr else ""
            log.warning(
                "[VideoComposite/per_clip_mux] pillarbox %s failed: %s",
                entry["line_id"], stderr[:200],
            )
            report.append(
                f"  pillarbox {entry['line_id']}: FAILED ({stderr[:120]})"
            )
            pb_failures += 1
    if sync_ext_total > 0 or sync_trunc_total > 0:
        report.append(
            f"per_clip_mux: BUG-LOCAL-031 sync corrections applied -- "
            f"total extend +{sync_ext_total:.2f}s, total truncate "
            f"-{sync_trunc_total:.2f}s"
        )

    if not pillarboxed:
        raise RuntimeError(
            "per_clip_mux: no segments survived pillarbox pass "
            "(check ffmpeg invocations + HuMo clip integrity)"
        )
    if pb_failures:
        report.append(
            f"per_clip_mux: WARNING {pb_failures} clip(s) lost during "
            f"pillarbox pass; proceeding with {len(pillarboxed)} survivors"
        )

    # 2b. BUG-LOCAL-128 fix: re-pillarbox the ACTUAL surviving last
    # clip with tail pad. Locate the timeline entry whose line_id
    # matches `pillarboxed[-1].stem` (stripped of "pb_" prefix), then
    # call _pillarbox_humo_silent again with extend_tail_s set. If
    # the re-pad call itself fails, log loudly and continue without
    # the pad -- the user gets a clear signal in the report and audio
    # may be tail-truncated but everything else still ships.
    surviving_last = pillarboxed[-1]
    surviving_line_id = surviving_last.stem
    if surviving_line_id.startswith("pb_"):
        surviving_line_id = surviving_line_id[3:]
    surviving_entry = next(
        (e for e in timeline if e["line_id"] == surviving_line_id),
        None,
    )
    if surviving_entry is None:
        log.warning(
            "[VideoComposite/per_clip_mux] could not locate timeline "
            "entry for surviving last clip %s; skipping tail pad",
            surviving_line_id,
        )
        report.append(
            f"  tail-pad: SKIPPED (no timeline match for {surviving_line_id})"
        )
    else:
        try:
            # BUG-LOCAL-030: re-pillarbox via the same layered helper so
            # the tail-pad call produces a frame consistent with the
            # rest of the timeline (LTX fill or HuMo pillar+backdrop).
            #
            # BUG-LOCAL-031 Track 1 (2026-05-03 EVENING): re-probe and
            # re-compute the sync extension for the surviving last clip
            # so this re-pillarbox call applies BOTH the per-clip
            # duration match AND the BUG-LOCAL-128 tail-pad. Without
            # this, the re-pillarbox would clobber the sync extension
            # already applied in the first loop above, leaving the
            # final clip un-padded vs its audio target.
            _surv_audio_target = float(surviving_entry.get("dur_s") or 0.0)
            _surv_video_actual = (
                _PROBE.probe_duration_s(surviving_entry["clip_path"], ffprobe=ffprobe)
                if _PROBE is not None else 0.0
            )
            _surv_sync_extend = 0.0
            _surv_truncate: float | None = None
            if (
                _PROBE is not None
                and _surv_video_actual > 0.0
                and _surv_audio_target > 0.0
            ):
                _gap, _action = _PROBE.duration_gap_s(
                    _surv_audio_target, _surv_video_actual,
                )
                if _action == "extend":
                    _surv_sync_extend = _gap
                elif _action == "truncate":
                    _surv_truncate = _surv_audio_target
            _combined_extend = _surv_sync_extend + _TAIL_PAD_S
            _layered_per_clip_silent(
                clip=surviving_entry["clip_path"],
                speaker_role=surviving_entry.get("speaker_role", ""),
                canvas_w=canvas_w, canvas_h=canvas_h,
                canvas_fps=canvas_fps,
                humo_pillar_w=humo_pillar_w,
                humo_pillar_h=humo_target_h,
                background_png=background_png,
                out_path=surviving_last, ffmpeg=ffmpeg,
                extend_tail_s=_combined_extend,
                truncate_to_s=_surv_truncate,
            )
            report.append(
                f"  tail-pad: +{_TAIL_PAD_S:.3f}s on {surviving_line_id} "
                f"(BUG-128) on top of +{_surv_sync_extend:.3f}s sync "
                f"extension (BUG-031) -- combined +{_combined_extend:.3f}s"
            )
            log.info(
                "[VideoComposite/per_clip_mux] tail-pad %.3fs (BUG-128) + "
                "%.3fs sync (BUG-031) on surviving last clip %s",
                _TAIL_PAD_S, _surv_sync_extend, surviving_line_id,
            )
        except subprocess.CalledProcessError as exc:
            stderr = exc.stderr.decode("utf-8", errors="replace") if exc.stderr else ""
            log.warning(
                "[VideoComposite/per_clip_mux] tail-pad on %s FAILED; "
                "trailing audio may be truncated by -shortest: %s",
                surviving_line_id, stderr[:200],
            )
            report.append(
                f"  tail-pad: FAILED on {surviving_line_id} "
                f"({stderr[:120]}) -- audio may truncate"
            )

    # 3. concat-demuxer the silent pillarboxed clips with -c copy.
    list_file = seg_dir / "concat.txt"
    list_file.write_text(
        "\n".join(f"file '{s.as_posix()}'" for s in pillarboxed),
        encoding="utf-8",
    )
    silent_combined = seg_dir / "silent_combined.mp4"
    cmd = [
        ffmpeg, "-y", "-loglevel", "warning",
        "-f", "concat", "-safe", "0",
        "-i", str(list_file),
        "-c", "copy",   # NO re-encode -- pillarbox already produced
                        # uniform H.264 yuv420p at canvas dims.
        str(silent_combined),
    ]
    subprocess.run(cmd, check=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    report.append(
        f"per_clip_mux: concat OK -> silent_combined {silent_combined.name}"
    )

    # BUG-LOCAL-030 long-form hardening (2026-05-03 EVENING, post
    # round-robin risk-#10 review): immediately reclaim the per-clip
    # pillarbox intermediates now that silent_combined.mp4 holds the
    # full assembled timeline. On a long-form episode (>5 min, ~100
    # per-line clips x ~5-15 MB each) this saves 0.5-1.5 GB of
    # transient disk before the final mux + RTXUpscale phases. Best-
    # effort: any unlink failure is logged, never raised; spacesaver
    # still owns the final cleanup of seg_dir if these stragglers
    # survive.
    _cleaned = 0
    for _pb in pillarboxed:
        try:
            _pb.unlink(missing_ok=True)
            _cleaned += 1
        except Exception as _exc:
            log.warning(
                "[VideoComposite/per_clip_mux] intermediate cleanup "
                "%s failed: %s", _pb.name, _exc,
            )
    if _cleaned:
        report.append(
            f"per_clip_mux: reclaimed {_cleaned} pillarbox intermediate(s)"
        )

    # BUG-LOCAL-084 Fix 4 (2026-05-04 LATE): duration-contract assertion.
    # silent_combined and procgen audio MUST agree within one canvas frame
    # (40 ms at 25 fps).  If they disagree by more than the tolerance, log
    # loudly so the regression is visible, and tail-pad the video side so
    # the mux's `-shortest` truncates an inaudible video tail rather than
    # chopping the master audio.  With Fixes 1-3 in place the totals
    # should match natively; this is belt-and-suspenders for any future
    # regression.
    _MUX_TOL_S = 0.04
    try:
        _v_dur = _ffprobe_dur(silent_combined, ffprobe) or 0.0
        _a_dur = _ffprobe_dur(procgen, ffprobe) or 0.0
        _gap = _a_dur - _v_dur
        report.append(
            f"per_clip_mux: duration contract -- "
            f"video {_v_dur:.3f}s | audio {_a_dur:.3f}s | "
            f"delta {_gap:+.3f}s (tol={_MUX_TOL_S:.3f}s)"
        )
        if abs(_gap) > _MUX_TOL_S:
            log.warning(
                "[VideoComposite/per_clip_mux] BUG-084 duration contract "
                "VIOLATED: video %.3fs vs audio %.3fs (delta %+.3fs, tol %.3fs). "
                "%s",
                _v_dur, _a_dur, _gap, _MUX_TOL_S,
                "Tail-padding video so -shortest truncates inaudible video, "
                "not audio." if _gap > 0 else
                "Video LONGER than audio -- -shortest will truncate trailing "
                "video; audio C7 preserved.",
            )
            if _gap > _MUX_TOL_S:
                # Audio overruns video: tail-pad the silent_combined by gap+
                # 0.05s safety so the mux -shortest cuts the freeze-frame
                # video tail instead of the trailing audio.
                _pad_target = _v_dur + _gap + 0.05
                _padded = silent_combined.with_name(
                    silent_combined.stem + "_tailpad.mp4"
                )
                _pad_cmd = [
                    ffmpeg, "-y", "-loglevel", "warning",
                    "-i", str(silent_combined),
                    "-vf", f"tpad=stop_mode=clone:stop_duration={_gap + 0.05:.3f}",
                    "-c:v", "libx264", "-preset", "veryfast",
                    "-crf", "16", "-pix_fmt", "yuv420p",
                    "-r", str(canvas_fps),
                    "-an",
                    str(_padded),
                ]
                try:
                    subprocess.run(
                        _pad_cmd, check=True,
                        stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                    )
                    silent_combined = _padded
                    log.info(
                        "[VideoComposite/per_clip_mux] BUG-084 tail-pad "
                        "applied: %s now %.3fs (target %.3fs)",
                        _padded.name, _ffprobe_dur(_padded, ffprobe) or 0.0,
                        _pad_target,
                    )
                    report.append(
                        f"per_clip_mux: BUG-084 tail-pad +{_gap + 0.05:.3f}s "
                        f"applied to silent_combined"
                    )
                except subprocess.CalledProcessError as exc:
                    stderr = exc.stderr.decode("utf-8", errors="replace") if exc.stderr else ""
                    log.warning(
                        "[VideoComposite/per_clip_mux] BUG-084 tail-pad "
                        "failed: %s -- proceeding with -shortest (audio "
                        "may be truncated by %.3fs)",
                        stderr[:200], _gap,
                    )
    except Exception as _dur_exc:  # noqa: BLE001
        log.warning(
            "[VideoComposite/per_clip_mux] BUG-084 duration-contract probe "
            "FAILED (%s); proceeding without assertion",
            _dur_exc,
        )

    # 4. Mux silent_combined video + procgen master-mix audio with
    # -c copy throughout.  This is the C7-critical step: audio
    # passes through without re-encode.  -shortest trims any audio
    # overhang past the combined video length.
    cmd = [
        ffmpeg, "-y", "-loglevel", "warning",
        "-i", str(silent_combined),
        "-i", str(procgen),
        "-map", "0:v",   # video from concatenated HuMo
        "-map", "1:a",   # audio from procgen master mix
        "-c:v", "copy",
        "-c:a", "copy",
        "-shortest",
        str(out_mp4),
    ]
    subprocess.run(cmd, check=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE)

    elapsed = time.time() - t0
    report.append(
        f"per_clip_mux: assembled {out_mp4.name} in {elapsed:.1f}s "
        f"(audio passthrough, 0 re-encodes downstream of SignalLostVideo)"
    )
    return out_mp4, report


def _render_humo_concat_mode(
    *,
    ledger: dict,
    clips_dir: Path,
    procgen: Path,
    out_mp4: Path,
    canvas_w: int,
    canvas_h: int,
    canvas_fps: int,
    humo_target_h: int,
    fallback_clip_length: float,
    ffmpeg: str,
    ffprobe: str,
) -> tuple[Path, list[str]]:
    """Build the final mp4 in humo_concat mode.

    Pipeline:
      1. Sort ledger.clips[] by start_s, build (clip_path, start_s, dur_s)
         tuples honouring REAL master-mix timestamps (not cumulative).
      2. Resolve radio bookend image (or procgen-frame fallback).
      3. For each pair of adjacent clips with a gap between them,
         create a gap segment: bookend image + master_mix audio slice.
      4. For each HuMo clip, normalize to canvas dims keeping native
         audio (mechanical lip-sync guarantee).
      5. ffmpeg concat-demuxer joins all segments in time order.

    Returns (final_mp4_path, report_lines).
    """
    report: list[str] = []
    t0 = time.time()

    # 1. Build timeline from ledger.clips[] using real master-mix start_s
    ledger_clips = ledger.get("clips") or []
    timeline: list[tuple[Path, float, float]] = []
    for entry in ledger_clips:
        line_id = str(entry.get("line_id") or "")
        if not line_id:
            continue
        cp = Path(entry.get("mp4_path") or "")
        if not cp.exists():
            cp = clips_dir / f"{line_id}.mp4"
        if not cp.exists():
            log.info(
                "[VideoComposite/humo_concat] skip %s: clip not on disk",
                line_id,
            )
            continue
        start_s = float(entry.get("start_s") or 0.0)
        dur_s = float(entry.get("dur_s") or 0.0)
        if dur_s <= 0:
            dur_s = _ffprobe_dur(cp, ffprobe) or float(fallback_clip_length)
        timeline.append((cp, start_s, dur_s))
    if not timeline:
        raise RuntimeError("humo_concat: no usable HuMo clips in ledger.clips[]")
    timeline.sort(key=lambda t: t[1])

    # 2. Episode duration (from procgen so we cover trailing music)
    episode_dur = _ffprobe_dur(procgen, ffprobe) or (timeline[-1][1] + timeline[-1][2])
    report.append(
        f"humo_concat: {len(timeline)} HuMo clip(s), episode duration "
        f"{episode_dur:.2f}s"
    )

    # 3. Resolve bookend image
    seg_dir = out_mp4.parent / "_humo_concat_segments"
    seg_dir.mkdir(parents=True, exist_ok=True)
    bookend = _resolve_bookend_image(ledger, procgen, seg_dir, ffmpeg)
    report.append(f"humo_concat: bookend image = {bookend.name}")

    # 4. Build segment list (alternating gap, clip, gap, ...)
    segments: list[Path] = []
    cursor = 0.0
    for i, (clip_path, start_s, dur_s) in enumerate(timeline):
        if start_s - cursor > 0.05:  # 50ms tolerance for float drift
            gap_path = seg_dir / f"gap_{i:03d}.mp4"
            try:
                _make_gap_segment(
                    bookend, procgen, cursor, start_s,
                    canvas_w, canvas_h, canvas_fps,
                    gap_path, ffmpeg,
                )
                segments.append(gap_path)
            except Exception as exc:
                log.warning(
                    "[VideoComposite/humo_concat] gap[%d, %.2f-%.2f] failed: %s",
                    i, cursor, start_s, exc,
                )
        clip_seg = seg_dir / f"clip_{i:03d}.mp4"
        try:
            _normalize_humo_segment(
                clip_path, canvas_w, canvas_h, canvas_fps,
                humo_target_h, clip_seg, ffmpeg,
            )
            segments.append(clip_seg)
        except Exception as exc:
            log.warning(
                "[VideoComposite/humo_concat] clip[%d] %s normalize failed: %s",
                i, clip_path.name, exc,
            )
            continue
        cursor = start_s + dur_s
    # Trailing gap
    if cursor < episode_dur - 0.05:
        try:
            tail_seg = seg_dir / "gap_999.mp4"
            _make_gap_segment(
                bookend, procgen, cursor, episode_dur,
                canvas_w, canvas_h, canvas_fps,
                tail_seg, ffmpeg,
            )
            segments.append(tail_seg)
        except Exception as exc:
            log.warning(
                "[VideoComposite/humo_concat] trailing gap %.2f-%.2f failed: %s",
                cursor, episode_dur, exc,
            )

    if not segments:
        raise RuntimeError("humo_concat: no segments produced")
    report.append(f"humo_concat: {len(segments)} segment(s) ready for concat")

    # 5. Concat-demuxer assembly
    list_file = seg_dir / "concat.txt"
    list_file.write_text(
        "\n".join(f"file '{s.as_posix()}'" for s in segments),
        encoding="utf-8",
    )
    cmd = [
        ffmpeg, "-y", "-loglevel", "warning",
        "-f", "concat", "-safe", "0",
        "-i", str(list_file),
        "-c:v", "libx264", "-pix_fmt", "yuv420p", "-crf", "18", "-preset", "fast",
        "-c:a", "aac", "-b:a", "192k", "-ar", "48000",
        str(out_mp4),
    ]
    subprocess.run(cmd, check=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
    elapsed = time.time() - t0
    report.append(
        f"humo_concat: assembled {out_mp4.name} in {elapsed:.1f}s"
    )
    return out_mp4, report


