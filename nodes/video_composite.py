    @staticmethod
    def _end_of_run_cleanup():
        """End-of-run VRAM release (BUG-LOCAL-123 fix 2026-04-30).

        VideoComposite is the LAST node in every OTR run. ComfyUI's
        ``model_management`` deliberately keeps loaded models resident
        across prompts to amortize load time, but for OTR that means
        HuMo (16.5 GB) + WanTE + WanVAE + Whisper stay parked in VRAM
        between consecutive runs. The next run then OOMs when Mistral-
        Nemo's _prefill tries to allocate KV cache.

        This helper fires unconditionally in execute()'s finally block
        so the next prompt starts with a clean VRAM slate, regardless
        of whether the current run succeeded, failed, or raised.

        Idempotent and bounded: never raises, always logs.
        """
        log.info("[VideoComposite] end-of-run cleanup: unloading all models")
        try:
            import comfy.model_management as mm  # type: ignore
            mm.unload_all_models()
            log.info("[VideoComposite] end-of-run: unload_all_models() OK")
        except Exception as exc:  # noqa: BLE001
            log.warning(
                "[VideoComposite] end-of-run unload_all_models() failed: %s",
                exc,
            )
        try:
            import comfy.model_management as mm  # type: ignore
            mm.soft_empty_cache(force=True)
            log.info(
                "[VideoComposite] end-of-run: soft_empty_cache(force=True) OK"
            )
        except Exception as exc_mm:  # noqa: BLE001
            log.warning(
                "[VideoComposite] end-of-run soft_empty_cache failed: %s; "
                "trying torch fallback",
                exc_mm,
            )
            try:
                import gc
                import torch  # type: ignore
                gc.collect()
                if torch.cuda.is_available():
                    torch.cuda.synchronize()
                    torch.cuda.empty_cache()
                log.info(
                    "[VideoComposite] end-of-run: torch fallback cleanup OK"
                )
            except Exception as exc:  # noqa: BLE001
                log.warning(
                    "[VideoComposite] end-of-run torch fallback failed: %s",
                    exc,
                )

    def execute(self, **kwargs):
        """Thin wrapper around ``_execute_body`` that guarantees
        end-of-run VRAM cleanup via a finally block.  See
        ``_end_of_run_cleanup`` for rationale (BUG-LOCAL-123)."""
        try:
            return self._execute_body(**kwargs)
        finally:
            self._end_of_run_cleanup()

    def _execute_body(
        self,
        procgen_video_path: str,
        clips_dir: str,
        ledger_json: str,
        blend_mode: str = "lighten",
        blend_opacity: float = 0.0,
        canvas_width: int = 1920,
        canvas_height: int = 1080,
        canvas_fps: int = 25,
        humo_target_height: int = 1080,
        fallback_clip_length: float = 7.0,
        ffmpeg: str = "ffmpeg",
        cleanup_clips_after_assembly: bool = False,
        audio_source: str = "master_mix_per_clip_mux",
        strict_c7: bool = True,
    ):
        # `cleanup_clips_after_assembly` widget is wired but the deletion
        # logic itself is deferred (would happen post-assembly when the
        # final mp4 is verified). Until then we just accept the kwarg
        # without crashing and log if it was requested -- ComfyUI passes
        # every INPUT_TYPES key as a kwarg, so the parameter MUST be in
        # the signature even if the side-effect isn't implemented yet.
        if cleanup_clips_after_assembly:
            log.info(
                "[VideoComposite] cleanup_clips_after_assembly=True requested "
                "but deletion logic is not yet implemented -- clips kept "
                "for now (this is a known TODO, not a regression)."
            )
        t_start = time.time()
        ffprobe = ffmpeg.replace("ffmpeg", "ffprobe") if ffmpeg.endswith("ffmpeg") else "ffprobe"

        # ---- Validate inputs ----
        procgen = Path(procgen_video_path.strip())
        if not procgen.exists():
            return ("", f"error: procgen_video_path not found: {procgen}")
        clips = Path(clips_dir.strip())
        if not clips.exists():
            return ("", f"error: clips_dir not found: {clips}")
        if not (shutil.which(ffmpeg) or Path(ffmpeg).exists()):
            return ("", f"error: ffmpeg not found at {ffmpeg!r}")

        ledger, ledger_path = _load_ledger_with_path(ledger_json)
        episode_id = ledger.get("episode_id", "episode")

        # ---- Resolve output_dir (intermediate composite, per-episode) ----
        # output_dir = ComfyUI/output/otr/episodes/<episode_id>/composited/
        # This is the INTERMEDIATE 832x480 composite. The downstream
        # OTR_RTXUpscale stage reads this and writes the final mp4 to
        # the OBS-watched dir at output/otr/obs/<episode_id>.mp4
        # (see otr_obs_dir). Per-episode workspace puts every working
        # file for THIS episode under one parent (audio, stills,
        # portraits, videos, composited) for tidy organization.
        out_dir = episodes_for_obs_dir(episode_id)
        out_dir.mkdir(parents=True, exist_ok=True)
        out_mp4 = out_dir / f"{episode_id}.mp4"

        # ---- Branch on audio_source ----
        # master_mix_per_clip_mux: 2026-04-30 C7 byte-perfect mode.
        # Pillarbox + concat HuMo clips silent, then mux master mix
        # audio onto the combined video with -c copy.  Falls through
        # to humo_concat if the pillarbox/concat/mux pipeline fails
        # AND strict_c7 is OFF.  When strict_c7 is ON (the default),
        # the failure raises so a silent C7-violating fallback
        # cannot ship.
        # 2026-04-30 round-robin hardening: every outcome stamps
        # ledger.meta.audio_path_selected + audio_path_reason so a
        # post-mortem can tell at a glance which tier produced the
        # final mp4 and why.
        def _stamp_audio_path(selected, reason):
            """Loud ledger signal.  Survives a failed save_ledger_safe
            (warns, doesn't raise)."""
            if ledger_path is None:
                return
            try:
                meta = ledger.setdefault("meta", {})
                meta["audio_path_selected"] = selected
                meta["audio_path_reason"] = reason
                meta["audio_source"] = selected  # back-compat alias
                from . import _otr_ledger as _OTRL  # type: ignore
                _OTRL.save_ledger_safe(ledger_path, ledger)
            except Exception as stamp_exc:  # noqa: BLE001
                log.warning(
                    "[VideoComposite] audio_path_selected=%s stamp "
                    "failed: %s", selected, stamp_exc,
                )

        if audio_source == "master_mix_per_clip_mux":
            log.info(
                "[VideoComposite] audio_source=master_mix_per_clip_mux -- "
                "C7 byte-perfect path (pillarbox + concat + mux, "
                "0 audio re-encodes downstream of SignalLostVideo); "
                "strict_c7=%s", strict_c7,
            )
            try:
                final_mp4, mux_report = _render_master_mix_per_clip_mux_mode(
                    ledger=ledger,
                    clips_dir=clips,
                    procgen=procgen,
                    out_mp4=out_mp4,
                    canvas_w=canvas_width,
                    canvas_h=canvas_height,
                    canvas_fps=canvas_fps,
                    humo_target_h=humo_target_height,
                    fallback_clip_length=fallback_clip_length,
                    ffmpeg=ffmpeg,
                    ffprobe=ffprobe,
                )
            except Exception as exc:
                # LOUD failure signal: log.exception + report-line
                # WARNING prefix.  Then either raise (strict mode) or
                # fall through to humo_concat (will re-encode audio).
                log.exception(
                    "[VideoComposite] master_mix_per_clip_mux FAILED: %s",
                    exc,
                )
                if strict_c7:
                    _stamp_audio_path(
                        "FAILED:master_mix_per_clip_mux",
                        f"strict_c7=True; not falling back to a re-encoding "
                        f"tier; reason={exc!r}",
                    )
                    raise RuntimeError(
                        "VideoComposite: strict_c7=True and "
                        "master_mix_per_clip_mux failed.  Refusing to "
                        "fall back to humo_concat (which 3x AAC re-encodes "
                        "audio and breaks C7).  Set strict_c7=False to "
                        f"allow the legacy fallback chain.  Reason: {exc}"
                    ) from exc
                # strict_c7 OFF: stamp the loud signal, fall through.
                _stamp_audio_path(
                    "humo_concat (FALLBACK from master_mix_per_clip_mux)",
                    f"per_clip_mux raised {exc!r}; strict_c7=False so "
                    f"falling back to humo_concat (audio will re-encode "
                    f"3x to AAC; C7 byte-identity NOT preserved)",
                )
            else:
                # Success path.  Stamp loud + return.
                _stamp_audio_path(
                    "master_mix_per_clip_mux",
                    "ok (zero audio re-encodes downstream of SignalLostVideo)",
                )
                if ledger_path is not None:
                    try:
                        ledger["final_video_path"] = str(final_mp4)
                        from . import _otr_ledger as _OTRL  # type: ignore
                        _OTRL.save_ledger_safe(ledger_path, ledger)
                    except Exception as stamp_exc:  # noqa: BLE001
                        log.warning(
                            "[VideoComposite] per_clip_mux final_video "
                            "stamp failed: %s", stamp_exc,
                        )
                report_lines = [
                    f"VideoComposite (master_mix_per_clip_mux mode, "
                    f"strict_c7={strict_c7})",
                    f"  episode_id: {episode_id}",
                    f"  out_mp4:    {final_mp4}",
                    "",
                    *mux_report,
                ]
                elapsed = time.time() - t_start
                log.info(
                    "[VideoComposite] per_clip_mux complete in %.1fs: %s",
                    elapsed, final_mp4,
                )
                return (str(final_mp4), "\n".join(report_lines))

        # humo_concat mode: bypass the existing 2-layer filter graph
        # entirely. Build a concat-demuxer pipeline where each HuMo
        # clip keeps its NATIVE audio (mechanical lip-sync) and gap
        # windows are filled with the radio bookend image + master_mix
        # audio slices (talking-radio identity continuous).
        if audio_source == "humo_concat" or audio_source == "master_mix_per_clip_mux":
            log.info(
                "[VideoComposite] audio_source=humo_concat -- routing to "
                "concat-demuxer pipeline (perfect lip-sync, bookend gaps)"
            )
            try:
                final_mp4, concat_report = _render_humo_concat_mode(
                    ledger=ledger,
                    clips_dir=clips,
                    procgen=procgen,
                    out_mp4=out_mp4,
                    canvas_w=canvas_width,
                    canvas_h=canvas_height,
                    canvas_fps=canvas_fps,
                    humo_target_h=humo_target_height,
                    fallback_clip_length=fallback_clip_length,
                    ffmpeg=ffmpeg,
                    ffprobe=ffprobe,
                )
            except Exception as exc:
                # BUG-LOCAL-126 fix (2026-05-01, second-Opus review):
                # Mirror the strict_c7 wrap that already exists at the
                # master_mix_per_clip_mux -> humo_concat edge.  Without
                # this, a humo_concat failure silently falls through to
                # the legacy master_mix path at line ~1194 below, which
                # uses `-c:a aac -b:a 192k` -- a real C7 violation.
                log.exception(
                    "[VideoComposite] humo_concat failed: %s", exc,
                )
                if strict_c7:
                    _stamp_audio_path(
                        "FAILED:humo_concat",
                        f"strict_c7=True; refusing master_mix legacy "
                        f"fallback (re-encodes audio AAC@192k); "
                        f"reason={exc!r}",
                    )
                    raise RuntimeError(
                        "VideoComposite: strict_c7=True and humo_concat "
                        "failed.  Refusing to fall back to master_mix "
                        "legacy mode (which AAC-re-encodes audio at "
                        "192k and breaks C7).  Set strict_c7=False to "
                        f"allow the legacy fallback chain.  Reason: {exc}"
                    ) from exc
                # strict_c7 OFF: stamp the loud signal, fall through.
                _stamp_audio_path(
                    "master_mix (FALLBACK from humo_concat)",
                    f"humo_concat raised {exc!r}; strict_c7=False so "
                    f"falling back to legacy master_mix (audio WILL "
                    f"re-encode to AAC@192k; C7 byte-identity NOT "
                    f"preserved)",
                )
                # Fall through to master_mix path on any failure.
            else:
                # Stamp final_video_path in ledger same as master_mix path.
                if ledger_path is not None:
                    try:
                        ledger["final_video_path"] = str(final_mp4)
                        with open(ledger_path, "w", encoding="utf-8") as _f:
                            json.dump(ledger, _f, indent=2)
                    except Exception as _stamp_exc:  # noqa: BLE001
                        log.warning(
                            "[VideoComposite] humo_concat ledger stamp failed: %s",
                            _stamp_exc,
                        )
                report_text = (
                    "VideoComposite (humo_concat mode)\n"
                    + "\n".join(f"  {ln}" for ln in concat_report)
                )
                return (str(final_mp4), report_text)

        # ---- Defense-in-depth: legacy master_mix re-encodes audio ----
        # BUG-LOCAL-126 (2026-05-01, second-Opus review): this block
        # uses `-c:a aac -b:a 192k` further down (line ~1225).  If
        # anyone reaches this path with strict_c7=True (current default
        # is True), the run MUST fail loudly -- regardless of which
        # upstream branch fell through.  Catches future fallthrough
        # bugs that don't honor strict_c7 at their own except clauses.
        if strict_c7:
            _stamp_audio_path(
                "FAILED:legacy_master_mix_blocked",
                "strict_c7=True; legacy master_mix uses -c:a aac -b:a "
                "192k which violates C7 byte-identity. Refusing to "
                "execute it. Set strict_c7=False if you accept the "
                "C7 violation.",
            )
            raise RuntimeError(
                "VideoComposite: strict_c7=True and execution reached "
                "the legacy master_mix path. This path AAC-re-encodes "
                "audio at 192k and breaks C7 byte-identity. If you "
                "see this raise, an upstream branch fell through "
                "without honoring strict_c7. Either fix that branch "
                "or set strict_c7=False at the workflow level."
            )

        # ---- Build clip timeline (master_mix mode) ----
        timeline = _build_clip_timeline(ledger, clips, fallback_clip_length, ffprobe)
        if not timeline:
            return ("", f"error: no HuMo clips found in {clips}")
        episode_dur = _ffprobe_dur(procgen, ffprobe) or sum(d for _, _, d in timeline)

        # ---- Build filter graph ----
        filter_graph, inputs_list = _build_filter_graph(
            procgen_video=procgen,
            timeline=timeline,
            canvas_w=canvas_width,
            canvas_h=canvas_height,
            canvas_fps=canvas_fps,
            humo_h=humo_target_height,
            blend_mode=blend_mode,
            blend_opacity=blend_opacity,
            episode_dur=episode_dur,
        )

        # ---- Build ffmpeg command ----
        cmd: list[str] = [ffmpeg, "-y", "-loglevel", "warning"]
        for inp in inputs_list:
            cmd.extend(["-i", str(inp)])
        cmd.extend([
            "-filter_complex", filter_graph,
            "-map", "[v]",
            "-map", "0:a",
            "-c:v", "libx264",
            "-preset", "medium",
            "-crf", "18",
            "-pix_fmt", "yuv420p",
            "-c:a", "aac",
            "-b:a", "192k",
            str(out_mp4),
        ])
        log.info("[VideoComposite] ffmpeg: %s", " ".join(cmd[:6] + ["..."] + [cmd[-1]]))
        log.debug("[VideoComposite] full cmd: %s", cmd)

        report = [
            f"VideoComposite: episode={episode_id}",
            f"  procgen={procgen.name}",
            f"  clips_dir={clips}",
            f"  timeline: {len(timeline)} clip(s), episode_dur={episode_dur:.2f}s",
            f"  blend_mode={blend_mode} opacity={blend_opacity}",
            f"  canvas={canvas_width}x{canvas_height}@{canvas_fps}fps",
        ]
        for clip_path, s, d in timeline[:8]:
            report.append(f"    {clip_path.name}: t={s:.2f}-{(s+d):.2f}s")
        if len(timeline) > 8:
            report.append(f"    ... +{len(timeline) - 8} more")

        # ---- Run ffmpeg ----
        try:
            r = subprocess.run(
                cmd, capture_output=True, text=True, check=False, timeout=900,
            )
            if r.returncode != 0:
                report.append(f"  FFMPEG FAIL rc={r.returncode}")
                report.append(f"  stderr: {r.stderr[-800:]}")
                return (str(out_mp4), "\n".join(report))
        except subprocess.TimeoutExpired:
            return (str(out_mp4), "error: ffmpeg timeout (>900s)")
        except Exception as exc:
            return (str(out_mp4), f"error: ffmpeg launch failed: {exc}")

        total_ms = int((time.time() - t_start) * 1000)
        report.append(f"  ffmpeg complete in {total_ms} ms")
        report.append(f"  out: {out_mp4}")

        # ---- BUG-LOCAL-089: write final_video_path back to ledger ----
        # The broadcast-tree mp4 is the canonical "this episode is
        # done" artifact. Persist its path in the ledger so OBS
        # schedulers, post-mortem tools, and any downstream re-runs
        # can resolve it via ledger lookup. Skipped silently when the
        # ledger came from inline JSON (no on-disk source).
        if ledger_path is not None:
            try:
                ledger["final_video_path"] = str(out_mp4)
                ledger["total_episode_dur_s"] = (
                    float(episode_dur) if episode_dur else
                    ledger.get("total_episode_dur_s")
                )
                with open(ledger_path, "w", encoding="utf-8") as f:
                    json.dump(ledger, f, indent=2, ensure_ascii=False)
                log.info(
                    "[VideoComposite] ledger updated: final_video_path -> %s",
                    out_mp4.name,
                )
                report.append(
                    f"  ledger updated: final_video_path={out_mp4.name}"
                )
            except Exception as exc:
                log.warning(
                    "[VideoComposite] ledger final_video_path write-back failed: %s",
                    exc,
                )
                report.append(f"  ledger write-back FAILED: {exc}")
        else:
            log.info(
                "[VideoComposite] inline ledger (no path) -- "
                "skipping final_video_path write-back"
            )
        return (str(out_mp4), "\n".join(report))


