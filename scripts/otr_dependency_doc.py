#!/usr/bin/env python
"""Generate `docs/DEPENDENCIES.md` -- everything OTR needs, in install order.

    python scripts/otr_dependency_doc.py

WHY IT IS GENERATED. The Python package list comes from requirements.txt, so it
cannot drift from what pip actually installs. Only the parts pip CANNOT express
-- system libraries, isolated venvs, and model weights -- are declared here, and
each says why it is not just a pip line.

WHAT THIS DOCUMENT IS FOR. A person on a machine that has never run OTR. The
authoring box cannot answer that question about itself: it accreted `accelerate`
transitively from ComfyUI core, `pycairo` from another pack, `feedparser` from
something forgotten. None were installed deliberately, and requirements.txt was
never what made them present. A rented pod found all three in one day precisely
because it inherits nothing.
"""
from __future__ import annotations

import io
import os
import re
import sys

_HERE = os.path.dirname(os.path.abspath(__file__))
_REPO = os.path.dirname(_HERE)

#: Things pip cannot install, with the symptom you get without them.
SYSTEM_LIBS = [
    ("libcairo2-dev, pkg-config", "apt-get install -y libcairo2-dev pkg-config",
     "pycairo is a C extension. Without these, `pip install pycairo` fails at "
     "metadata generation -- and because `import cairo` sits UNGUARDED inside "
     "the draw function, every viz_mandala frame and every scope overlay then "
     "raises ImportError at RENDER time, not at install."),
    ("ffmpeg", "apt-get install -y ffmpeg  (or ships with the image)",
     "muxing, captions and the credits concat. Note: having ffmpeg proves "
     "nothing about NVENC -- most containers expose CUDA for compute but not "
     "libnvidia-encode.so.1, and OTR falls back to CPU encoding automatically."),
]

#: Engines that run in their OWN venv, on purpose.
ISOLATED = [
    ("indextts2", "index-tts", "https://github.com/index-tts/index-tts.git",
     "pins >=3.10,<3.12 -- build the venv with `uv venv --python 3.11`",
     "OTR_INDEXTTS2_VENV / _DIR / _WORKER",
     "the default character voice. Non-commercial licence, so it is NOT "
     "offered for the announcer. Needs reference WAVs (below)."),
    ("chatterbox", "chatterbox", "pip: chatterbox-tts soundfile torch torchaudio",
     "own venv; torch pinned separately from ComfyUI's",
     "OTR_CHATTERBOX_VENV / _WORKER",
     "MIT, commercial-clean, and announcer-capable -- one of only two cloning "
     "engines the announcer accepts."),
    ("dia", "dia", "pip: git+https://github.com/nari-labs/dia.git",
     "own venv; torch pinned separately",
     "OTR_DIA_VENV / _WORKER",
     "Apache, the second commercial-clean cloner, also announcer-capable."),
]

_WHY_ISOLATED = (
    "Each pins torch/transformers versions that would brick ComfyUI's own venv, "
    "so they run as supervised subprocess workers over line-delimited JSON with "
    "ZERO shared torch.")


def requirements() -> list:
    out = []
    path = os.path.join(_REPO, "requirements.txt")
    for line in io.open(path, encoding="utf-8"):
        raw = line.split("#")[0].strip()
        if raw:
            out.append(raw)
    return out


def render() -> str:
    L, A = [], None
    A = L.append
    A("# Everything OTR needs, and how to install it\n")
    A("**GENERATED by `scripts/otr_dependency_doc.py`. Do not hand-edit.**\n")
    A("Written for a machine that has never run OTR. If you are on the box "
      "that developed it, this list will look longer than your experience "
      "suggests -- that is the point. A developer machine accretes packages "
      "invisibly: `accelerate` arrived transitively from ComfyUI core, "
      "`pycairo` from another node pack, `feedparser` from something long "
      "forgotten. None were installed deliberately, and a fresh machine "
      "inherits none of them.\n")

    A("## The short version\n")
    A("```bash\n"
      "# 1. system libraries pip cannot provide (Linux)\n"
      "sudo apt-get install -y libcairo2-dev pkg-config ffmpeg\n\n"
      "# 2. the pack and its Python dependencies -- INTO THE PYTHON COMFYUI RUNS\n"
      "git clone -b v2.0-alpha https://github.com/jbrick2070/ComfyUI-OldTimeRadio\n"
      "<comfyui-python> -m pip install -r ComfyUI-OldTimeRadio/requirements.txt\n\n"
      "# 3. model weights for the lane you want\n"
      "python scripts/otr_fetch_lane_weights.py haunted\n\n"
      "# 4. check what actually landed\n"
      "python scripts/otr_venv_audit.py\n"
      "```\n")
    A("**Step 2 is where installs go wrong.** ComfyUI usually runs its own "
      "venv, and `python3 -m pip` installs somewhere else. That single mistake "
      "produced three separate failures in one day -- a writer that died at 18 "
      "seconds, an RSS fetch that blamed the feeds, and a quantiser that "
      "reported a missing library it had been given. Find the right "
      "interpreter:\n")
    A("```bash\n"
      "python3 -c \"import folder_paths,os;print(os.path.dirname(folder_paths.__file__))\"\n"
      "# then use that tree's venv python, e.g. <root>/.venv/bin/python\n"
      "```\n")

    A("## 1. System libraries -- pip cannot install these\n")
    A("| package | install | why, and what breaks without it |")
    A("|---|---|---|")
    for name, cmd, why in SYSTEM_LIBS:
        A("| `%s` | `%s` | %s |" % (name, cmd, why))
    A("")

    A("## 2. Python packages\n")
    A("From `requirements.txt`, which is the authority -- this list is read "
      "from it:\n")
    A("```")
    for line in requirements():
        A(line)
    A("```\n")

    A("## 3. Isolated-venv voice engines\n")
    A("%s\n" % _WHY_ISOLATED)
    A("**Do NOT edit their adapters to make paths work on your OS.** Qualified "
      "voice routes are pinned to an adapter fingerprint, so any edit "
      "un-qualifies every route audited against it and the cast silently falls "
      "back to an ordinary draw -- the episode still renders, which is what "
      "makes it easy to miss. Use the environment variables instead.\n")
    for name, dirname, source, build, envs, why in ISOLATED:
        A("### `%s`\n" % name)
        A("* install to: `<comfy-root>/%s` (or anywhere, and set the env var)" % dirname)
        A("* source: `%s`" % source)
        A("* build: %s" % build)
        A("* env: `%s`" % envs)
        A("* %s\n" % why)
    A("**Reference WAVs** for cloning engines live at "
      "`<models_root>/TTS/refs/<engine>/*.wav`, one per cast voice. They ship "
      "with nothing. Without a resolvable reference the engine refuses by name "
      "and there is no fallback.\n")

    A("## 4. Model weights\n")
    A("See [MODEL_ASSET_INDEX.md](MODEL_ASSET_INDEX.md) -- generated from the "
      "engine code, and the only place file names, repo ids and sizes are "
      "recorded. `scripts/otr_fetch_lane_weights.py --list` shows which lanes "
      "install with one command.\n")
    A("Two environment variables decide where everything lands:\n")
    A("```\n"
      "OTR_COMFYUI_MODELS_ROOT   the models root\n"
      "HF_HOME                   MUST be <models_root>/huggingface\n"
      "```\n")
    A("Setting `HF_HOME` anywhere else does not relocate the cache, it ADDS "
      "one. That mistake cost 84 GB of duplicate weights and surfaced only as "
      "a disk-quota error on a half-empty volume.\n")

    A("## 5. Verify\n")
    A("```bash\n"
      "python scripts/otr_venv_audit.py     # what is imported vs declared vs installed\n"
      "curl -s $URL/object_info | grep -c OTR_   # non-zero means the pack loaded\n"
      "```\n")
    A("`otr_venv_audit.py` reports and never gates. Two things it cannot see, "
      "stated so you do not over-trust it: a declared wheel that needs a system "
      "library underneath it, and packages your DEPENDENCIES import at runtime "
      "-- `bitsandbytes` never appears in OTR's source because transformers "
      "imports it, not us.\n")
    return "\n".join(L) + "\n"


def main() -> int:
    text = render()
    dest = os.path.join(_REPO, "docs", "DEPENDENCIES.md")
    io.open(dest, "w", encoding="utf-8", newline="\n").write(text)
    print("wrote %s (%d bytes)" % (dest, len(text)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
