def test_english_and_no_meta_are_byte_identical_for_the_provenance_credit():
    cases = [
        ({"status": "public_domain_us", "source_label": "Hamlet"},
         "adapted from Hamlet (public domain)"),
        ({"status": "public_domain_us"}, "adapted from a public domain work"),
        ({"status": "cc0", "source_label": "X"}, "adapted from X (CC0 / public domain)"),
        ({"status": "research_only", "source_label": "X"},
         "adapted from X (research use only)"),
        ({"status": "research_only"},
         "adapted from a source cleared for research use only"),
        ({"status": "licensed_noncommercial", "source_label": "Macbeth",
          "license_label": "CC BY-NC 3.0"},
         "adapted from Macbeth, used under CC BY-NC 3.0"),
        ({"status": "licensed_noncommercial", "license_label": "CC BY-NC 3.0"},
         "used under CC BY-NC 3.0"),
        ({"status": "licensed_commercial", "source_label": "Macbeth"},
         "adapted from Macbeth"),
        ({"status": "synthetic"},
         "an original story generated by machine for this broadcast"),
        ({"status": "mystery"}, ""),
    ]
    for prov, want in cases:
        assert PROV.printed_credit_line(prov) == want, prov
        assert PROV.printed_credit_line(prov, episode_meta={"episode_language": "en"}) == want
        assert PROV.printed_credit_line(prov, episode_meta={}) == want


def test_the_provenance_credit_follows_the_row():
    prov = {"status": "public_domain_us", "source_label": "Hamlet"}
    assert PROV.printed_credit_line(prov, episode_meta={"episode_language": "es"}) \
        == "adaptado de Hamlet (dominio público)"
    assert PROV.printed_credit_line({"status": "synthetic"},
                                    episode_meta={"episode_language": "ja"}) \
        == "この放送のために機械が生成したオリジナル作品"


def test_the_freely_wrap_is_byte_identical_in_english_and_follows_the_row():
    assert VL.non_verbatim_credit_line("adapted from Macbeth (CC BY-NC 3.0)") == \
        "freely adapted from Macbeth (CC BY-NC 3.0)"
    assert VL.non_verbatim_credit_line("used under CC BY-NC 3.0") == \
        "freely adapted from the source; used under CC BY-NC 3.0"
    assert VL.non_verbatim_credit_line("") == "freely adapted from the source"
    es = {"episode_language": "es"}
    assert VL.non_verbatim_credit_line("adaptado de Macbeth (CC BY-NC 3.0)", episode_meta=es) \
        == "libremente adaptado de Macbeth (CC BY-NC 3.0)"
    assert VL.non_verbatim_credit_line("bajo licencia CC BY-NC 3.0", episode_meta=es) \
        == "libremente adaptado de la fuente; bajo licencia CC BY-NC 3.0"
    hi = {"episode_language": "hi"}
    assert VL.non_verbatim_credit_line("Macbeth से रूपांतरित (CC BY-NC 3.0)", episode_meta=hi) \
        == "Macbeth से रूपांतरित (CC BY-NC 3.0) (मुक्त रूपांतरण)"


def test_my_story_printed_credit_follows_the_row():
    assert SI.credits_source_line("Ada Byron") == \
        "a story by Ada Byron, produced by machine for this broadcast"
    assert SI.credits_source_line("") == SI.ANONYMOUS_CREDIT
    assert SI.credits_source_line("Ada Byron", episode_meta={"episode_language": "en"}) == \
        "a story by Ada Byron, produced by machine for this broadcast"
    assert SI.credits_source_line("Ada Byron", episode_meta={"episode_language": "fr"}) == \
        "une histoire de Ada Byron, produite par machine pour cette émission"
    receipt = SI.attribution_receipt("Ada Byron", episode_meta={"episode_language": "fr"})
    assert receipt["credits_source_line"].startswith("une histoire de Ada Byron")


