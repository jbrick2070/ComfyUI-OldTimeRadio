"""The printed SOURCE line on the credits roll follows the episode row.

Operator pick 2026-09-18: a bank-by-language matrix. Per-bank sentences live
in banks.json as scalar `credits_source_line_<iso>` keys; the Python sentences
(provenance credit, the "freely adapted" wrap, My Story's credit, the
writer tail's models line) and the roll's SOURCE labels are row `credits`
keys. English and no meta are byte-identical to the old literals. CPU only.
"""
from __future__ import annotations

import inspect

import pytest

from nodes import _otr_episode_languages as EL
from nodes import _otr_provenance as PROV
from nodes import _otr_story_input as SI
from nodes import _otr_story_routing as RT
from nodes import _otr_verbatim_lane as VL

ROWS = [row for row in EL.load_registry()[0] if row.admitted]
NON_ENGLISH = [row for row in ROWS if row.iso != "en"]
BANKS_WITH_LINE = ("original", "scifi_news_pro", "my_story")


