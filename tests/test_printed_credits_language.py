@pytest.mark.parametrize("bank_id", BANKS_WITH_LINE)
def test_every_bank_default_line_has_every_non_english_row(bank_id):
    defaults = RT.get_bank(bank_id).defaults or {}
    assert defaults["credits_source_line"].strip()
    for row in NON_ENGLISH:
        line = defaults["credits_source_line_" + row.iso]
        assert line.strip(), (bank_id, row.iso)
        assert line != defaults["credits_source_line"], (bank_id, row.iso)


