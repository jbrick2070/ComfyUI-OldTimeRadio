@pytest.mark.parametrize("row", ROWS, ids=[r.iso for r in ROWS])
def test_every_row_formats_every_printed_template(row):
    meta = {"episode_language": row.iso}
    for status in ("public_domain_us", "cc0", "research_only", "synthetic",
                   "licensed_noncommercial"):
        with_src = PROV.printed_credit_line(
            {"status": status, "source_label": "Work", "license_label": "L"},
            episode_meta=meta)
        assert with_src.strip(), (row.iso, status)
        if status != "synthetic":
            assert "Work" in with_src, (row.iso, status)
        assert PROV.printed_credit_line({"status": status, "license_label": "L"},
                                        episode_meta=meta).strip()
    wrapped = VL.non_verbatim_credit_line(with_src, episode_meta=meta)
    assert wrapped.strip() and wrapped != with_src, row.iso
    assert VL.non_verbatim_credit_line("", episode_meta=meta).strip()
    assert "Ada" in SI.credits_source_line("Ada", episode_meta=meta)
    assert SI.credits_source_line("", episode_meta=meta).strip()
    assert "m1" in row.credits["credit_models_used"].format(models="m1")


