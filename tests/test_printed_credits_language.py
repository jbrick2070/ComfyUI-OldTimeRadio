def test_an_unreadable_registry_never_costs_a_printed_credit(monkeypatch):
    """Every printed-credit site keeps its English literal when the registry
    itself cannot be read -- a label may never fail a roll or a run."""
    def _broken(*_a, **_k):
        raise EL.EpisodeLanguageError("registry unreadable")

    monkeypatch.setattr(EL, "row_by_label", _broken)
    monkeypatch.setattr(EL, "row_from_meta", _broken)
    assert EL.credits_or_english(None) == {}
    assert EL.credits_or_english({"episode_language": "es"}) == {}
    prov = {"status": "public_domain_us", "source_label": "Hamlet"}
    assert PROV.printed_credit_line(prov, episode_meta={"episode_language": "es"}) == \
        "adapted from Hamlet (public domain)"
    assert VL.non_verbatim_credit_line("adapted from X", episode_meta={"episode_language": "es"}) \
        == "freely adapted from X"
    assert SI.credits_source_line("Ada", episode_meta={"episode_language": "es"}) == \
        "a story by Ada, produced by machine for this broadcast"
    from nodes import otr_credits_roll as roll
    chrome = roll._credits_chrome({"episode_language": "es"})
    assert set(chrome) == set(EL._REQUIRED_CREDITS)
    assert all(str(v).strip() for v in chrome.values())
    assert chrome["source_label"] == "SOURCE"
    from nodes import _otr_writer_tail as tail
    src = inspect.getsource(tail._stamp_model_call_provenance)
    # The tail keeps its English literal inside an except around the lookup.
    assert '"Story generation models used: " + (' in src
    assert src.index("credits_or_english(meta)") < src.index('"Story generation models used: " + (')
    assert "except Exception" in src[src.index("credits_or_english(meta)"):]
