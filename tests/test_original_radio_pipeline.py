class TestRegistry:
    def test_real_registry_loads_with_original_row(self):
        ids = ROUTING.list_bank_ids()
        assert "original" in ids
        assert ids[-1] == "custom_source_bank"  # "+ Add Your Own" stays last

    def test_bank_row_shape(self):
        bank = ROUTING.get_bank("original")
        assert bank.runnable is True
        assert bank.fetcher == "" and bank.interpreter == ""
        assert bank.default_story_pipeline == "original_multi_pass"
        d = bank.defaults
        assert d.get("hud_origin_label") == "STORY ORIGIN"
        assert "generated by machine" in d.get("credits_source_line", "")
        assert "coda_mode" not in d  # V4 lock 8: dead config class

    def test_pipeline_row_shape(self):
        pipe = ROUTING.get_pipeline("original_multi_pass")
        assert pipe.executable is True          # sweep 4b elif demands it
        assert pipe.requires_source_contract is False
        assert pipe.declared_seams == frozenset({
            "original_concept_system", "original_select_system",
            "original_brief_system",
        })

    def test_pack_carries_12_stages_and_required_subset(self):
        bank = ROUTING.get_bank("original")
        pack = ROUTING.resolve_story_pack("original")
        assert len(pack.prompt_stages) == 12
        assert set(bank.required_seams) <= set(pack.prompt_stages)
        for seam in (
            "original_concept_system",
            "original_select_system",
            "original_brief_system",
        ):
            assert pack.prompt_stages[seam].strip()

    def test_sweep_demands_executable_true(self):
        # The r2 M2 pin, both directions: the REAL set passes (loaded
        # above); a fixture with executable:false raises the 4b elif.
        reg = ROUTING._ensure_loaded()
        bad_pipe = dataclasses.replace(
            reg.pipelines["original_multi_pass"], executable=False)
        pipelines = dict(reg.pipelines)
        pipelines["original_multi_pass"] = bad_pipe
