class TestInterpreterAdapter:
    def test_adapter_runs_and_restamps_both_surfaces(self):
        resolved = {
            "source_meta": {"kind": "original_llm",
                            "spark_atoms": {"place": "the lock"}},
            "num_characters": 2,
            "creative_writing_model": "c-model",
        }
        meta = {"source_meta": dict(resolved["source_meta"])}
        adapter = W._make_original_interpreter(
            creative_fn=_seq_fn(_CONCEPT_JSON, _SELECT_JSON),
            resolved=resolved, meta=meta,
        )
        bank = ROUTING.get_bank("original")
        briefs = adapter(bank=bank, payload={"ignored": "yes"},
                         technical_fn=_seq_fn(_BRIEFS_JSON),
                         model_id="t-model")
        assert briefs.casting_brief
        # r3 D3: the delta reached BOTH surfaces.
        for surface in (resolved["source_meta"], meta["source_meta"]):
            assert "selected_concept" in surface
            assert surface["model_ids"]["technical"] == "t-model"

    def test_adapter_without_atoms_fails_loud(self):
        adapter = W._make_original_interpreter(
            creative_fn=_seq_fn(_CONCEPT_JSON), resolved={"source_meta": {},
            "num_characters": 2, "creative_writing_model": "c"}, meta={},
        )
        with pytest.raises(ORR.OriginalBriefsError, match="spark_atoms"):
            adapter(bank=ROUTING.get_bank("original"), payload={},
                    technical_fn=_seq_fn(_BRIEFS_JSON), model_id="t")


